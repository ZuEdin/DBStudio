/**
 * AST Code Generator Plugin Architecture
 * Enables modular, extensible code generation for backend languages:
 * - Go GORM Structs & Migration
 * - Python SQLAlchemy 2.0 & Pydantic v2
 * - Rust Diesel & SQLx Schema
 * - C# Entity Framework Core 8
 * - Dynamic 3rd-party AST plugin registration
 */

import { Table, Relationship } from '../../types';

export interface CodeGenPluginOptions {
  includeValidation?: boolean;
  includeComments?: boolean;
  camelCaseProperties?: boolean;
  packageName?: string;
  tableNamePrefix?: string;
}

export interface GeneratedPluginOutput {
  fileName: string;
  language: string;
  code: string;
  description?: string;
}

export interface ICodeGenPlugin {
  id: string;
  name: string;
  language: string;
  runtimeTarget: string;
  category: 'orm' | 'types' | 'api' | 'migration';
  description: string;
  iconName: string;
  generate: (tables: Table[], relationships: Relationship[], options?: CodeGenPluginOptions) => GeneratedPluginOutput[];
}

/**
 * 1. Go GORM Plugin
 */
export const GoGormPlugin: ICodeGenPlugin = {
  id: 'plugin_go_gorm',
  name: 'Go (GORM & Gin ORM Models)',
  language: 'go',
  runtimeTarget: 'Go 1.22+ / GORM / Gin',
  category: 'orm',
  iconName: 'FileCode',
  description: 'Generiert idiomatische Go-Structs mit gorm: Tags, JSON-Bindings und GORM AutoMigrate DDL.',
  generate: (tables: Table[], relationships: Relationship[], options?: CodeGenPluginOptions) => {
    const pkg = options?.packageName || 'models';
    const outputs: GeneratedPluginOutput[] = [];

    let modelsCode = `// Code generated by DB Studio Pro AST Plugin Engine. DO NOT EDIT.
package ${pkg}

import (
\t"time"
\t"gorm.io/gorm"
)

`;

    for (const table of tables) {
      const structName = toPascalCase(table.name);
      modelsCode += `// ${structName} repräsentiert die Tabelle "${table.name}"\ntype ${structName} struct {\n`;

      for (const field of table.fields) {
        const fieldName = toPascalCase(field.name);
        const goType = mapToGoType(field.type, field.isNullable);
        const tags: string[] = [];

        // GORM tag
        const gormTags: string[] = [`column:${field.name}`];
        if (field.isPrimaryKey) gormTags.push('primaryKey');
        if (!field.isNullable && !field.isPrimaryKey) gormTags.push('not null');
        if (field.type === 'VARCHAR' && field.length) gormTags.push(`size:${field.length}`);

        tags.push(`gorm:"${gormTags.join(';')}"`);
        tags.push(`json:"${field.name}${field.isNullable ? ',omitempty' : ''}"`);

        modelsCode += `\t${fieldName.padEnd(20)} ${goType.padEnd(12)} \`${tags.join(' ')}\`\n`;
      }

      modelsCode += `}\n\n`;
      modelsCode += `// TableName gibt den expliziten Tabellennamen für GORM zurück\nfunc (${structName}) TableName() string {\n\treturn "${table.name}"\n}\n\n`;
    }

    // Migration helper
    let migrateCode = `package ${pkg}

import "gorm.io/gorm"

// AutoMigrateAll führt AutoMigration für alle Tabellen durch
func AutoMigrateAll(db *gorm.DB) error {
\treturn db.AutoMigrate(
${tables.map((t) => `\t\t&${toPascalCase(t.name)}{},`).join('\n')}
\t)
}
`;

    outputs.push({
      fileName: 'models.go',
      language: 'go',
      code: modelsCode,
      description: 'GORM Struct Definitionen mit Feld-Tags',
    });

    outputs.push({
      fileName: 'migrate.go',
      language: 'go',
      code: migrateCode,
      description: 'Automatischer GORM Migration-Runner',
    });

    return outputs;
  },
};

/**
 * 2. Python SQLAlchemy 2.0 & Pydantic v2 Plugin
 */
export const PythonSqlAlchemyPlugin: ICodeGenPlugin = {
  id: 'plugin_python_sqlalchemy',
  name: 'Python (SQLAlchemy 2.0 & Pydantic v2)',
  language: 'python',
  runtimeTarget: 'Python 3.11+ / FastAPI / SQLAlchemy 2.0',
  category: 'orm',
  iconName: 'Database',
  description: 'Generiert typisierte SQLAlchemy DeclarativeBase Models und Pydantic v2 Schemas für FastAPI.',
  generate: (tables: Table[], relationships: Relationship[], options?: CodeGenPluginOptions) => {
    const outputs: GeneratedPluginOutput[] = [];

    // SQLAlchemy Models
    let saCode = `# Code generated by DB Studio Pro AST Plugin Engine.
from __future__ import annotations
from datetime import datetime, date
from decimal import Decimal
from typing import Optional, List
from sqlalchemy import String, Integer, Numeric, Boolean, Date, DateTime, ForeignKey, Text
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

class Base(DeclarativeBase):
    pass

`;

    for (const table of tables) {
      const clsName = toPascalCase(table.name);
      saCode += `class ${clsName}(Base):\n`;
      saCode += `    __tablename__ = "${table.name}"\n\n`;

      for (const field of table.fields) {
        const pyType = mapToPythonType(field.type, field.isNullable);
        const colArgs: string[] = [];

        if (field.isPrimaryKey) colArgs.push('primary_key=True');
        if (!field.isNullable && !field.isPrimaryKey) colArgs.push('nullable=False');
        if (field.type === 'VARCHAR' && field.length) colArgs.push(`String(${field.length})`);

        saCode += `    ${field.name}: Mapped[${pyType}] = mapped_column(${colArgs.join(', ')})\n`;
      }
      saCode += '\n';
    }

    // Pydantic Schemas
    let pydanticCode = `# Pydantic v2 Schemas for FastAPI Data Validation
from __future__ import annotations
from datetime import datetime, date
from decimal import Decimal
from typing import Optional
from pydantic import BaseModel, ConfigDict, Field

`;

    for (const table of tables) {
      const clsName = toPascalCase(table.name);
      pydanticCode += `class ${clsName}Base(BaseModel):\n`;
      for (const field of table.fields) {
        if (field.isPrimaryKey) continue;
        const pyType = mapToPythonType(field.type, field.isNullable);
        pydanticCode += `    ${field.name}: ${pyType}\n`;
      }

      pydanticCode += `\nclass ${clsName}Create(${clsName}Base):\n    pass\n\n`;
      pydanticCode += `class ${clsName}Response(${clsName}Base):\n`;
      pydanticCode += `    model_config = ConfigDict(from_attributes=True)\n`;
      const pkField = table.fields.find((f) => f.isPrimaryKey) || table.fields[0];
      if (pkField) {
        pydanticCode += `    ${pkField.name}: ${mapToPythonType(pkField.type, false)}\n`;
      }
      pydanticCode += '\n';
    }

    outputs.push({
      fileName: 'models.py',
      language: 'python',
      code: saCode,
      description: 'SQLAlchemy 2.0 DeclarativeBase Tabellen-Klassen',
    });

    outputs.push({
      fileName: 'schemas.py',
      language: 'python',
      code: pydanticCode,
      description: 'Pydantic v2 Validierungs-Schemas für FastAPI',
    });

    return outputs;
  },
};

