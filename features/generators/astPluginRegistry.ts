export const RustDieselPlugin: ICodeGenPlugin = {
  id: 'plugin_rust_diesel',
  name: 'Rust (Diesel ORM & SQLx)',
  language: 'rust',
  runtimeTarget: 'Rust Edition 2021 / Diesel 2.1 / SQLx',
  category: 'orm',
  iconName: 'Cpu',
  description: 'Generiert typisierte Rust Structs mit serde, diesel table! Makros und SQLx Queryable Typen.',
  generate: (tables: Table[], relationships: Relationship[]) => {
    let rustCode = `// Generated by DB Studio Pro AST Plugin Engine
use serde::{Deserialize, Serialize};
use chrono::{NaiveDate, NaiveDateTime};

`;

    for (const table of tables) {
      const structName = toPascalCase(table.name);
      rustCode += `#[derive(Debug, Clone, Serialize, Deserialize, sqlx::FromRow)]\n`;
      rustCode += `pub struct ${structName} {\n`;

      for (const field of table.fields) {
        const rustType = mapToRustType(field.type, field.isNullable);
        rustCode += `    pub ${field.name}: ${rustType},\n`;
      }
      rustCode += `}\n\n`;
    }

    // Diesel table macros
    let schemaCode = `// Diesel table! schema declarations
diesel::table! {
`;
    for (const table of tables) {
      const pk = table.fields.find((f) => f.isPrimaryKey)?.name || 'id';
      schemaCode += `    ${table.name} (${pk}) {\n`;
      for (const field of table.fields) {
        schemaCode += `        ${field.name} -> ${mapToDieselSqlType(field.type)},\n`;
      }
      schemaCode += `    }\n`;
    }
    schemaCode += `}\n`;

    return [
      {
        fileName: 'models.rs',
        language: 'rust',
        code: rustCode,
        description: 'Rust Structs mit Serde & SQLx FromRow',
      },
      {
        fileName: 'schema.rs',
        language: 'rust',
        code: schemaCode,
        description: 'Diesel table! Makros für compile-time Type Checking',
      },
    ];
  },
};

