/**
 * Plugin Registry Singleton
 */
class AstPluginRegistry {
  private plugins: Map<string, ICodeGenPlugin> = new Map();

  constructor() {
    // Register Default Pre-installed Plugins
    this.registerPlugin(GoGormPlugin);
    this.registerPlugin(PythonSqlAlchemyPlugin);
    this.registerPlugin(RustDieselPlugin);
    this.registerPlugin(CSharpEfCorePlugin);
  }

  public registerPlugin(plugin: ICodeGenPlugin) {
    this.plugins.set(plugin.id, plugin);
  }

  public getPlugin(id: string): ICodeGenPlugin | undefined {
    return this.plugins.get(id);
  }

  public getAllPlugins(): ICodeGenPlugin[] {
    return Array.from(this.plugins.values());
  }
}

export const astPluginRegistry = new AstPluginRegistry();

// Helper Functions
function toPascalCase(str: string): string {
  if (!str) return 'Entity';
  return str
    .replace(/[^a-zA-Z0-9_]/g, '_')
    .split('_')
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join('');
}

function mapToGoType(type: string, isNullable: boolean): string {
  const upper = (type || 'VARCHAR').toUpperCase();
  let base = 'string';
  if (upper.includes('INT')) base = 'int64';
  else if (upper.includes('DEC') || upper.includes('FLOAT') || upper.includes('DOUBLE')) base = 'float64';
  else if (upper.includes('BOOL')) base = 'bool';
  else if (upper.includes('DATE') || upper.includes('TIME')) base = 'time.Time';
  else if (upper.includes('BLOB') || upper.includes('BIN')) base = '[]byte';

  return isNullable ? `*${base}` : base;
}

function mapToPythonType(type: string, isNullable: boolean): string {
  const upper = (type || 'VARCHAR').toUpperCase();
  let base = 'str';
  if (upper.includes('INT')) base = 'int';
  else if (upper.includes('DEC') || upper.includes('FLOAT') || upper.includes('DOUBLE')) base = 'Decimal';
  else if (upper.includes('BOOL')) base = 'bool';
  else if (upper.includes('DATE')) base = 'date';
  else if (upper.includes('TIME')) base = 'datetime';
  else if (upper.includes('BLOB') || upper.includes('BIN')) base = 'bytes';

  return isNullable ? `Optional[${base}] = None` : base;
}

function mapToRustType(type: string, isNullable: boolean): string {
  const upper = (type || 'VARCHAR').toUpperCase();
  let base = 'String';
  if (upper.includes('INT')) base = 'i64';
  else if (upper.includes('DEC') || upper.includes('FLOAT') || upper.includes('DOUBLE')) base = 'f64';
  else if (upper.includes('BOOL')) base = 'bool';
  else if (upper.includes('DATE')) base = 'NaiveDate';
  else if (upper.includes('TIME')) base = 'NaiveDateTime';
  else if (upper.includes('BLOB') || upper.includes('BIN')) base = 'Vec<u8>';

  return isNullable ? `Option<${base}>` : base;
}

function mapToDieselSqlType(type: string): string {
  const upper = (type || 'VARCHAR').toUpperCase();
  if (upper.includes('INT')) return 'BigInt';
  if (upper.includes('DEC') || upper.includes('FLOAT') || upper.includes('DOUBLE')) return 'Double';
  if (upper.includes('BOOL')) return 'Bool';
  if (upper.includes('DATE')) return 'Date';
  if (upper.includes('TIME')) return 'Timestamp';
  return 'Text';
}

function mapToCSharpType(type: string, isNullable: boolean): string {
  const upper = (type || 'VARCHAR').toUpperCase();
  let base = 'string';
  if (upper.includes('INT')) base = 'long';
  else if (upper.includes('DEC')) base = 'decimal';
  else if (upper.includes('FLOAT') || upper.includes('DOUBLE')) base = 'double';
  else if (upper.includes('BOOL')) base = 'bool';
  else if (upper.includes('DATE') || upper.includes('TIME')) base = 'DateTime';
  else if (upper.includes('BLOB') || upper.includes('BIN')) base = 'byte[]';

  return (isNullable && base !== 'string') ? `${base}?` : base;
}
