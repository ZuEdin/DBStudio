import { Table, Relationship, TableGroup, Field, FieldType } from '../../../types/index';

export class DbmlTranspilerService {
  /**
   * Generates formatted DBML code from Tables, Relationships and Groups
   */
  public static tablesToDbml(
    tables: Table[],
    relationships: Relationship[],
    groups?: TableGroup[]
  ): string {
    const lines: string[] = [];

    lines.push('// DBML Schema generated by DB Studio Pro');
    lines.push('// Documentation: https://dbml.dbdiagram.io/docs/\n');

    // 1. Tables
    tables.forEach(table => {
      lines.push(`Table ${table.name} {`);
      table.fields.forEach(field => {
        const attributes: string[] = [];
        if (field.isPrimaryKey) attributes.push('pk');
        if (field.isAutoIncrement) attributes.push('increment');
        if (field.isUnique) attributes.push('unique');
        if (field.isNullable === false || field.allowNull === false) attributes.push('not null');
        if (field.defaultValue) attributes.push(`default: "${field.defaultValue}"`);
        if (field.comment) attributes.push(`note: "${field.comment.replace(/"/g, '\\"')}"`);

        const attrString = attributes.length > 0 ? ` [${attributes.join(', ')}]` : '';
        const fieldType = (field.type || 'varchar').toLowerCase();
        lines.push(`  ${field.name} ${fieldType}${attrString}`);
      });

      if (table.description) {
        lines.push(`\n  Note: '${table.description.replace(/'/g, "\\'")}'`);
      }
      lines.push('}\n');
    });

    // 2. Relationships (Refs)
    relationships.forEach(rel => {
      const parentTable = tables.find(t => t.id === rel.fromTableId);
      const parentField = parentTable?.fields.find(f => f.id === rel.fromFieldId);
      const childTable = tables.find(t => t.id === rel.toTableId);
      const childField = childTable?.fields.find(f => f.id === rel.toFieldId);

      if (parentTable && parentField && childTable && childField) {
        let symbol = '>';
        if (rel.type === '1:1') symbol = '-';
        else if (rel.type === 'n:m' || rel.type === 'N:M') symbol = '<>';

        let settings = '';
        const settingsList: string[] = [];
        if (rel.onDelete && rel.onDelete !== 'NO ACTION') {
          settingsList.push(`delete: ${rel.onDelete.toLowerCase().replace(' ', '_')}`);
        }
        if (rel.onUpdate && rel.onUpdate !== 'NO ACTION') {
          settingsList.push(`update: ${rel.onUpdate.toLowerCase().replace(' ', '_')}`);
        }
        if (settingsList.length > 0) {
          settings = ` [${settingsList.join(', ')}]`;
        }

        lines.push(`Ref: ${childTable.name}.${childField.name} ${symbol} ${parentTable.name}.${parentField.name}${settings}`);
      }
    });

    // 3. TableGroups
    if (groups && groups.length > 0) {
      lines.push('\n// Domain Groups / Sub-Schemas');
      groups.forEach(g => {
        // Find tables in this group
        // If we don't have tableId mapping directly in group, check if any exists
        lines.push(`TableGroup ${g.name.replace(/\s+/g, '_')} {`);
        if (g.comment) {
          lines.push(`  // Note: ${g.comment}`);
        }
        lines.push('}');
      });
    }

    return lines.join('\n');
  }

  /**
   * Parses DBML syntax into structured Tables and Relationships
   */
  public static parseDbmlToSchema(dbmlCode: string): {
    tables: Table[];
    relationships: Relationship[];
    errors: string[];
  } {
    const tables: Table[] = [];
    const relationships: Relationship[] = [];
    const errors: string[] = [];

    try {
      const cleanCode = dbmlCode.replace(/\/\*[\s\S]*?\*\/|\/\/.*/g, '');
      const tableBlocks: string[] = cleanCode.match(/Table\s+([a-zA-Z0-9_]+)\s*\{([\s\S]*?)\}/gi) || [];

      tableBlocks.forEach((block: string) => {
        const headerMatch = block.match(/Table\s+([a-zA-Z0-9_]+)/i);
        const tableName = headerMatch ? headerMatch[1] : `Table_${tables.length + 1}`;
        const tableId = crypto.randomUUID();

        const bodyMatch = block.match(/\{([\s\S]*?)\}/);
        if (!bodyMatch) return;
        const bodyContent = bodyMatch[1];

        const fields: Field[] = [];
        const lines = bodyContent.split('\n');

        lines.forEach(line => {
          const trimmed = line.trim();
          if (!trimmed || trimmed.startsWith('Note:') || trimmed.startsWith('//')) return;

          const fieldMatch = trimmed.match(/^([a-zA-Z0-9_]+)\s+([a-zA-Z0-9_()]+)(?:\s*\[(.*?)\])?/);
          if (fieldMatch) {
            const fieldName = fieldMatch[1];
            const rawType = fieldMatch[2].toUpperCase();
            const rawAttrs = fieldMatch[3] || '';

            let normalizedType: FieldType = 'VARCHAR';
            if (rawType.includes('INT')) normalizedType = 'INTEGER';
            else if (rawType.includes('UUID')) normalizedType = 'UUID';
            else if (rawType.includes('TEXT')) normalizedType = 'TEXT';
            else if (rawType.includes('DATE')) normalizedType = 'DATE';
            else if (rawType.includes('TIME')) normalizedType = 'DATETIME';
            else if (rawType.includes('BOOL')) normalizedType = 'BOOLEAN';
            else if (rawType.includes('DECIMAL') || rawType.includes('NUMERIC')) normalizedType = 'DECIMAL';
            else if (rawType.includes('FLOAT') || rawType.includes('DOUBLE')) normalizedType = 'DOUBLE';
            else if (rawType.includes('JSON')) normalizedType = 'JSON';

            const isPk = /pk/i.test(rawAttrs);
            const isAutoInc = /increment/i.test(rawAttrs);
            const isUnique = /unique/i.test(rawAttrs);
            const isNotNull = /not\s+null/i.test(rawAttrs);

            const noteMatch = rawAttrs.match(/note:\s*["']([^"']+)["']/i);
            const comment = noteMatch ? noteMatch[1] : undefined;

            fields.push({
              id: crypto.randomUUID(),
              name: fieldName,
              type: normalizedType,
              isPrimaryKey: isPk,
              isAutoIncrement: isAutoInc,
              isUnique: isUnique,
              allowNull: !isNotNull,
              isNullable: !isNotNull,
              comment
            });
          }
        });

        tables.push({
          id: tableId,
          name: tableName,
          fields
        });
      });

      // Parse Relationships (Refs)
      const refMatches: string[] = cleanCode.match(/Ref:\s*([a-zA-Z0-9_]+)\.([a-zA-Z0-9_]+)\s*([><\-=]+)\s*([a-zA-Z0-9_]+)\.([a-zA-Z0-9_]+)/gi) || [];

      refMatches.forEach((refStr: string) => {
        const m = refStr.match(/Ref:\s*([a-zA-Z0-9_]+)\.([a-zA-Z0-9_]+)\s*([><\-=]+)\s*([a-zA-Z0-9_]+)\.([a-zA-Z0-9_]+)/i);
        if (m) {
          const fromTName = m[4];
          const fromFName = m[5];
          const toTName = m[1];
          const toFName = m[2];
          const symbol = m[3];

          const parentTable = tables.find(t => t.name.toLowerCase() === fromTName.toLowerCase());
          const parentField = parentTable?.fields.find(f => f.name.toLowerCase() === fromFName.toLowerCase());
          const childTable = tables.find(t => t.name.toLowerCase() === toTName.toLowerCase());
          const childField = childTable?.fields.find(f => f.name.toLowerCase() === toFName.toLowerCase());

          if (parentTable && parentField && childTable && childField) {
            let relType: '1:1' | '1:n' | 'n:m' = '1:n';
            if (symbol === '-' || symbol === '=') relType = '1:1';
            else if (symbol === '<>') relType = 'n:m';

            relationships.push({
              id: crypto.randomUUID(),
              fromTableId: parentTable.id,
              fromFieldId: parentField.id,
              toTableId: childTable.id,
              toFieldId: childField.id,
              fromTable: parentTable.name,
              fromField: parentField.name,
              toTable: childTable.name,
              toField: childField.name,
              type: relType,
              referentialIntegrity: true,
              onDelete: 'CASCADE',
              onUpdate: 'CASCADE'
            });
          }
        }
      });

    } catch (err: any) {
      errors.push(`Fehler beim DBML-Parsing: ${err?.message || String(err)}`);
    }

    return { tables, relationships, errors };
  }
}
