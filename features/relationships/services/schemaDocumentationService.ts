import { Table, Relationship, Field, TableGroup } from '../../../types/index';

export class SchemaDocumentationService {
  /**
   * Generates a comprehensive Data Dictionary in Markdown format
   */
  public static generateMarkdownDictionary(
    tables: Table[],
    relationships: Relationship[],
    groups?: TableGroup[]
  ): string {
    const lines: string[] = [];

    lines.push('# 📖 Datenbankschema & Data-Dictionary');
    lines.push(`*Erstellt am: ${new Date().toLocaleDateString('de-DE')} | Generiert mit DB Studio Pro*\n`);

    lines.push('## 📑 Inhaltsverzeichnis');
    tables.forEach(t => {
      lines.push(`- [${t.name}](#tabelle-${t.name.toLowerCase()})`);
    });
    lines.push('- [Relationen & Fremdschlüssel](#beziehungsmatrix)');
    lines.push('\n---\n');

    // 1. Tables
    tables.forEach(table => {
      lines.push(`### <a id="tabelle-${table.name.toLowerCase()}"></a>📊 Tabelle: \`${table.name}\``);
      if (table.description) {
        lines.push(`> **Beschreibung:** ${table.description}\n`);
      }

      lines.push('| Spalte | Typ | PK | FK | Nicht Null | Eindeutig | Standardwert | Beschreibung |');
      lines.push('|---|---|:---:|:---:|:---:|:---:|---|---|');

      table.fields.forEach(f => {
        const isFk = relationships.some(r => r.toTableId === table.id && r.toFieldId === f.id);
        const pkMarker = f.isPrimaryKey ? '🔑 **JA**' : '-';
        const fkMarker = isFk ? '🔗 **FK**' : '-';
        const notNullMarker = (f.isNullable === false || f.allowNull === false) ? '✓' : '-';
        const uniqueMarker = f.isUnique ? '✓' : '-';
        const defVal = f.defaultValue ? `\`${f.defaultValue}\`` : '-';
        const comment = f.comment || '-';

        lines.push(`| **\`${f.name}\`** | \`${f.type}\` | ${pkMarker} | ${fkMarker} | ${notNullMarker} | ${uniqueMarker} | ${defVal} | ${comment} |`);
      });

      lines.push('\n');
    });

    // 2. Relationship Matrix
    lines.push('### <a id="beziehungsmatrix"></a>🔗 Beziehungsmatrix (ER-Referenzen)\n');
    if (relationships.length === 0) {
      lines.push('*Keine expliziten Fremdschlüssel-Beziehungen definiert.*\n');
    } else {
      lines.push('| Von Tabelle | Von Spalte | Zu Tabelle (Eltern) | Zu Spalte (PK) | Typ | ON DELETE | ON UPDATE |');
      lines.push('|---|---|---|---|:---:|---|---|');

      relationships.forEach(r => {
        const fromT = tables.find(t => t.id === r.fromTableId);
        const fromF = fromT?.fields.find(f => f.id === r.fromFieldId);
        const toT = tables.find(t => t.id === r.toTableId);
        const toF = toT?.fields.find(f => f.id === r.toFieldId);

        lines.push(`| \`${toT?.name || r.toTableId}\` | \`${toF?.name || r.toFieldId}\` | \`${fromT?.name || r.fromTableId}\` | \`${fromF?.name || r.fromFieldId}\` | **${r.type}** | \`${r.onDelete || 'NO ACTION'}\` | \`${r.onUpdate || 'NO ACTION'}\` |`);
      });
    }

    return lines.join('\n');
  }

  /**
   * Generates a Prisma Schema (schema.prisma) from the database tables and relationships
   */
  public static generatePrismaSchema(tables: Table[], relationships: Relationship[]): string {
    const lines: string[] = [
      '// Prisma Schema generated by DB Studio Pro',
      'datasource db {',
      '  provider = "postgresql"',
      '  url      = env("DATABASE_URL")',
      '}',
      '',
      'generator client {',
      '  provider = "prisma-client-js"',
      '}',
      ''
    ];

    tables.forEach(table => {
      lines.push(`model ${this.toPascalCase(table.name)} {`);

      table.fields.forEach(field => {
        let prismaType = 'String';
        const t = field.type.toUpperCase();
        if (t.includes('INT')) prismaType = 'Int';
        else if (t.includes('BIGINT')) prismaType = 'BigInt';
        else if (t.includes('BOOL')) prismaType = 'Boolean';
        else if (t.includes('DATE') || t.includes('TIME')) prismaType = 'DateTime';
        else if (t.includes('DECIMAL') || t.includes('CURRENCY')) prismaType = 'Decimal';
        else if (t.includes('FLOAT') || t.includes('DOUBLE')) prismaType = 'Float';
        else if (t.includes('JSON')) prismaType = 'Json';

        const optional = (field.isNullable !== false && field.allowNull !== false && !field.isPrimaryKey) ? '?' : '';
        const attributes: string[] = [];

        if (field.isPrimaryKey) {
          if (field.type === 'UUID') {
            attributes.push('@id @default(uuid())');
          } else if (field.isAutoIncrement) {
            attributes.push('@id @default(autoincrement())');
          } else {
            attributes.push('@id');
          }
        }

        if (field.isUnique && !field.isPrimaryKey) {
          attributes.push('@unique');
        }

        if (field.defaultValue && !field.isPrimaryKey) {
          attributes.push(`@default("${field.defaultValue}")`);
        }

        const attrString = attributes.length > 0 ? ` ${attributes.join(' ')}` : '';
        lines.push(`  ${field.name.padEnd(16)} ${prismaType}${optional}${attrString}`);
      });

      lines.push('}\n');
    });

    return lines.join('\n');
  }

  /**
   * Generates TypeSpec definition
   */
  public static generateTypeSpec(tables: Table[]): string {
    const lines: string[] = [
      '// TypeSpec Schema definition generated by DB Studio Pro',
      'import "@typespec/http";',
      'import "@typespec/rest";',
      '',
      'namespace DatabaseSchema;\n'
    ];

    tables.forEach(t => {
      lines.push(`model ${this.toPascalCase(t.name)} {`);
      t.fields.forEach(f => {
        let tsType = 'string';
        const type = f.type.toUpperCase();
        if (type.includes('INT') || type.includes('FLOAT') || type.includes('DECIMAL')) tsType = 'int64';
        else if (type.includes('BOOL')) tsType = 'boolean';
        else if (type.includes('DATE')) tsType = 'utcDateTime';

        const opt = (f.isNullable !== false && f.allowNull !== false && !f.isPrimaryKey) ? '?' : '';
        lines.push(`  ${f.name}${opt}: ${tsType};`);
      });
      lines.push('}\n');
    });

    return lines.join('\n');
  }

  private static toPascalCase(str: string): string {
    return str
      .replace(/[-_](\w)/g, (_, c) => c.toUpperCase())
      .replace(/^\w/, c => c.toUpperCase());
  }
}
