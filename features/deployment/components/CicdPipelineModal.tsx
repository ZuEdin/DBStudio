import React, { useState } from 'react';
import { 
  CiConfig, 
  CiProvider, 
  CloudDeployTarget, 
  generateGitHubWorkflow, 
  generateGitLabCI 
} from '../services/cicdPipelineGenerator';
import { 
  GitBranch, 
  Check, 
  Copy, 
  Download, 
  ShieldCheck, 
  Database, 
  Bell, 
  Layers, 
  X, 
  Sparkles, 
  Play, 
  Cpu,
  CheckCircle2,
  ExternalLink
} from 'lucide-react';
import JSZip from 'jszip';

interface CicdPipelineModalProps {
  projectName: string;
  onClose: () => void;
  onShowToast?: (msg: string, type: 'success' | 'info' | 'warning' | 'error') => void;
}

export const CicdPipelineModal: React.FC<CicdPipelineModalProps> = ({
  projectName,
  onClose,
  onShowToast
}) => {
  const [config, setConfig] = useState<CiConfig>({
    provider: 'github',
    projectName: projectName || 'DBStudioApp',
    targetCloud: 'cloudrun',
    registry: 'ghcr',
    imageName: `${(projectName || 'db-studio-app').toLowerCase().replace(/[^a-z0-9]/g, '-')}-service`,
    enableLintAndTest: true,
    enableSecurityScan: true,
    enableDbMigration: true,
    enableSlackNotification: false,
    branch: 'main'
  });

  const [copied, setCopied] = useState(false);
  const [activeTab, setActiveTab] = useState<'editor' | 'secrets' | 'topology'>('editor');

  const yamlContent = config.provider === 'github'
    ? generateGitHubWorkflow(config)
    : generateGitLabCI(config);

  const filename = config.provider === 'github' ? 'deploy.yml' : '.gitlab-ci.yml';
  const filePath = config.provider === 'github' ? '.github/workflows/deploy.yml' : '.gitlab-ci.yml';

  const handleCopy = () => {
    navigator.clipboard.writeText(yamlContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
    onShowToast?.(`${filename} in die Zwischenablage kopiert!`, 'success');
  };

  const handleDownloadZip = async () => {
    try {
      const zip = new JSZip();
      if (config.provider === 'github') {
        const gh = zip.folder('.github')?.folder('workflows');
        gh?.file('deploy.yml', yamlContent);
      } else {
        zip.file('.gitlab-ci.yml', yamlContent);
      }
      zip.file('README-CI-CD.md', `# CI/CD Setup for ${config.projectName}\n\nGenerated by DB Studio Pro v3.0 Enterprise\n\nTarget Cloud: ${config.targetCloud}\nBranch: ${config.branch}\n`);

      const content = await zip.generateAsync({ type: 'blob' });
      const url = URL.createObjectURL(content);
      const a = document.createElement('a');
      a.href = url;
      a.download = `${config.projectName.toLowerCase()}-cicd-pipeline.zip`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
      onShowToast?.('CI/CD Pipeline-Paket erfolgreich heruntergeladen!', 'success');
    } catch (e: any) {
      onShowToast?.(`Fehler beim ZIP-Download: ${e.message}`, 'error');
    }
  };

  return (
    <div className="fixed inset-0 z-50 bg-black/75 backdrop-blur-sm flex items-center justify-center p-4 animate-in fade-in duration-200">
      <div className="bg-slate-900 border border-slate-700 rounded-2xl max-w-5xl w-full max-h-[90vh] flex flex-col shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="px-6 py-4 bg-slate-950 border-b border-slate-800 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-blue-500/20 border border-blue-500/30 flex items-center justify-center text-blue-400">
              <GitBranch size={22} className="animate-pulse" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="text-base font-bold text-white">Automatisierter CI/CD Pipeline Generator</h3>
                <span className="bg-blue-500/20 text-blue-400 border border-blue-500/30 text-[10px] font-mono px-2 py-0.5 rounded-full font-bold">
                  GitHub &amp; GitLab
                </span>
              </div>
              <p className="text-xs text-slate-400 mt-0.5">
                Vorkonfigurierte Pipelines für Tests, Docker Multi-Arch Builds, DB-Migrationen &amp; Cloud Deployment
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-white rounded-lg hover:bg-slate-800 transition-colors"
          >
            <X size={18} />
          </button>
        </div>

        {/* Configuration Bar */}
        <div className="px-6 py-3.5 bg-slate-950/90 border-b border-slate-800 grid grid-cols-2 md:grid-cols-4 gap-3 text-xs">
          <div>
            <label className="text-slate-400 font-medium block mb-1">CI/CD Plattform:</label>
            <select
              value={config.provider}
              onChange={(e) => setConfig(prev => ({ ...prev, provider: e.target.value as CiProvider }))}
              className="w-full bg-slate-900 border border-slate-700 rounded px-2.5 py-1.5 text-white text-xs font-semibold"
            >
              <option value="github">GitHub Actions</option>
              <option value="gitlab">GitLab CI/CD</option>
            </select>
          </div>

          <div>
            <label className="text-slate-400 font-medium block mb-1">Deployment Ziel:</label>
            <select
              value={config.targetCloud}
              onChange={(e) => setConfig(prev => ({ ...prev, targetCloud: e.target.value as CloudDeployTarget }))}
              className="w-full bg-slate-900 border border-slate-700 rounded px-2.5 py-1.5 text-white text-xs font-semibold"
            >
              <option value="cloudrun">Google Cloud Run</option>
              <option value="aws_ecs">AWS ECS (Fargate)</option>
              <option value="kubernetes">Kubernetes / Helm</option>
              <option value="caprover">CapRover / Docker Swarm</option>
            </select>
          </div>

          <div>
            <label className="text-slate-400 font-medium block mb-1">Container Registry:</label>
            <select
              value={config.registry}
              onChange={(e) => setConfig(prev => ({ ...prev, registry: e.target.value as any }))}
              className="w-full bg-slate-900 border border-slate-700 rounded px-2.5 py-1.5 text-white text-xs"
            >
              <option value="ghcr">GitHub Packages (ghcr.io)</option>
              <option value="dockerhub">Docker Hub (docker.io)</option>
            </select>
          </div>

          <div>
            <label className="text-slate-400 font-medium block mb-1">Git Branch:</label>
            <input
              type="text"
              value={config.branch}
              onChange={(e) => setConfig(prev => ({ ...prev, branch: e.target.value }))}
              className="w-full bg-slate-900 border border-slate-700 rounded px-2.5 py-1 text-white font-mono text-xs"
            />
          </div>
        </div>

        {/* Feature Toggles */}
        <div className="px-6 py-2.5 bg-slate-950/60 border-b border-slate-800 flex flex-wrap items-center gap-5 text-xs text-slate-300">
          <label className="flex items-center gap-2 cursor-pointer">
            <input
              type="checkbox"
              checked={config.enableLintAndTest}
              onChange={(e) => setConfig(prev => ({ ...prev, enableLintAndTest: e.target.checked }))}
              className="rounded bg-slate-800 border-slate-700 text-blue-500"
            />
            <span>ESLint &amp; Unit Tests</span>
          </label>

          <label className="flex items-center gap-2 cursor-pointer">
            <input
              type="checkbox"
              checked={config.enableSecurityScan}
              onChange={(e) => setConfig(prev => ({ ...prev, enableSecurityScan: e.target.checked }))}
              className="rounded bg-slate-800 border-slate-700 text-indigo-500"
            />
            <span className="flex items-center gap-1"><ShieldCheck size={13} className="text-indigo-400" /> Trivy Security Scan</span>
          </label>

          <label className="flex items-center gap-2 cursor-pointer">
            <input
              type="checkbox"
              checked={config.enableDbMigration}
              onChange={(e) => setConfig(prev => ({ ...prev, enableDbMigration: e.target.checked }))}
              className="rounded bg-slate-800 border-slate-700 text-emerald-500"
            />
            <span className="flex items-center gap-1"><Database size={13} className="text-emerald-400" /> Auto DB-Migration</span>
          </label>

          <label className="flex items-center gap-2 cursor-pointer">
            <input
              type="checkbox"
              checked={config.enableSlackNotification}
              onChange={(e) => setConfig(prev => ({ ...prev, enableSlackNotification: e.target.checked }))}
              className="rounded bg-slate-800 border-slate-700 text-amber-500"
            />
            <span className="flex items-center gap-1"><Bell size={13} className="text-amber-400" /> Slack Status-Webhook</span>
          </label>
        </div>

        {/* Content Area */}
        <div className="p-6 overflow-y-auto space-y-4 flex-1">
          <div className="flex items-center justify-between">
            <div className="flex items-center gap-2">
              <span className="text-xs font-bold text-slate-300">Generierte Pipeline-Konfiguration:</span>
              <code className="text-[11px] font-mono px-2 py-0.5 rounded bg-slate-800 text-blue-400 border border-slate-700">
                {filePath}
              </code>
            </div>
            <div className="flex items-center gap-2">
              <button
                onClick={handleCopy}
                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 text-xs font-bold transition-all cursor-pointer"
              >
                {copied ? <Check size={13} /> : <Copy size={13} />}
                <span>{copied ? 'Kopiert!' : 'YAML Kopieren'}</span>
              </button>
              <button
                onClick={handleDownloadZip}
                className="flex items-center gap-1.5 px-3.5 py-1.5 rounded-lg bg-blue-600 hover:bg-blue-500 text-white text-xs font-bold shadow-lg shadow-blue-600/30 transition-all cursor-pointer"
              >
                <Download size={13} />
                <span>ZIP Herunterladen</span>
              </button>
            </div>
          </div>

          <pre className="bg-slate-950 border border-slate-800 rounded-xl p-4 text-[11px] font-mono text-blue-300 overflow-x-auto max-h-80">
            <code>{yamlContent}</code>
          </pre>
        </div>

        {/* Footer */}
        <div className="px-6 py-3.5 bg-slate-950 border-t border-slate-800 flex items-center justify-between text-xs text-slate-400">
          <div className="flex items-center gap-2">
            <Sparkles size={14} className="text-blue-400" />
            <span>Bereit für automatisierte Zero-Downtime Deployments</span>
          </div>
          <button
            onClick={onClose}
            className="px-4 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-200 font-bold transition-all"
          >
            Schließen
          </button>
        </div>
      </div>
    </div>
  );
};
