/**
 * Supabase BaaS Plugin
 * Generates decoupled PostgreSQL DDL, Foreign Keys, RLS Policies, and TypeScript Client types.
 */

import { Table, Relationship } from '../../../types';
import { ICloudSyncProvider, CloudProviderExportResult } from '../../../types/cloudProvider';

export const SupabasePlugin: ICloudSyncProvider = {
  id: 'supabase',
  name: 'Supabase (PostgreSQL & RLS)',
  description: 'Generiert PostgreSQL DDL Tabellen, Row Level Security (RLS) Policies, Indizes und Supabase TypeScript Helper.',
  category: 'baas',
  generateExport: (tables: Table[], relationships: Relationship[]) => {
    let sqlDdl = `-- ============================================================================
-- Supabase Schema & Migration generated by DB Studio Pro (Decoupled BaaS Plugin)
-- ============================================================================

-- 1. Enable UUID Extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

`;

    // 1. Table definitions
    for (const table of tables) {
      sqlDdl += `-- Table: ${table.name}\n`;
      sqlDdl += `CREATE TABLE IF NOT EXISTS public."${table.name}" (\n`;

      const colDefs: string[] = [];
      for (const f of table.fields) {
        let colDef = `    "${f.name}" ${mapToPgType(f.type, f.length)}`;
        if (f.isPrimaryKey) colDef += ' PRIMARY KEY';
        if (!f.isNullable && !f.isPrimaryKey) colDef += ' NOT NULL';
        if (f.defaultValue) colDef += ` DEFAULT ${f.defaultValue}`;
        colDefs.push(colDef);
      }

      // Add created_at / updated_at standard metadata if not present
      if (!table.fields.some((f) => f.name.toLowerCase() === 'created_at')) {
        colDefs.push(`    "created_at" TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL`);
      }

      sqlDdl += colDefs.join(',\n');
      sqlDdl += `\n);\n\n`;

      // 2. Enable RLS
      sqlDdl += `-- Enable Row Level Security (RLS)\n`;
      sqlDdl += `ALTER TABLE public."${table.name}" ENABLE ROW LEVEL SECURITY;\n\n`;

      // Standard Policies
      sqlDdl += `-- Standard RLS Policies for ${table.name}\n`;
      sqlDdl += `CREATE POLICY "Allow authenticated read for ${table.name}" \n    ON public."${table.name}" FOR SELECT \n    TO authenticated \n    USING (true);\n\n`;
      sqlDdl += `CREATE POLICY "Allow authenticated insert for ${table.name}" \n    ON public."${table.name}" FOR INSERT \n    TO authenticated \n    WITH CHECK (true);\n\n`;
      sqlDdl += `CREATE POLICY "Allow authenticated update for ${table.name}" \n    ON public."${table.name}" FOR UPDATE \n    TO authenticated \n    USING (true);\n\n`;
    }

    // 2. Foreign Keys
    if (relationships && relationships.length > 0) {
      sqlDdl += `-- ============================================================================\n-- Foreign Key Constraints & Relationships\n-- ============================================================================\n`;
      for (const rel of relationships) {
        const fromTable = tables.find((t) => t.id === rel.fromTableId);
        const toTable = tables.find((t) => t.id === rel.toTableId);
        if (fromTable && toTable) {
          const fromFld = fromTable.fields.find((f) => f.id === rel.fromFieldId);
          const toFld = toTable.fields.find((f) => f.id === rel.toFieldId);
          if (fromFld && toFld) {
            sqlDdl += `ALTER TABLE public."${fromTable.name}" \n`;
            sqlDdl += `    ADD CONSTRAINT "fk_${fromTable.name}_${fromFld.name}" \n`;
            sqlDdl += `    FOREIGN KEY ("${fromFld.name}") REFERENCES public."${toTable.name}"("${toFld.name}") \n`;
            sqlDdl += `    ON DELETE ${rel.onDelete || 'CASCADE'} ON UPDATE CASCADE;\n\n`;
          }
        }
      }
    }

    // 3. Supabase TypeScript Client Helper
    let tsClientCode = `// Supabase Client Types generated by DB Studio Pro
import { createClient } from '@supabase/supabase-js';

export interface Database {
  public: {
    Tables: {
${tables
  .map(
    (t) => `      ${t.name}: {
        Row: {
${t.fields.map((f) => `          ${f.name}: ${mapToTsType(f.type, f.isNullable)};`).join('\n')}
        };
        Insert: {
${t.fields.map((f) => `          ${f.name}${f.isNullable || f.isPrimaryKey ? '?' : ''}: ${mapToTsType(f.type, f.isNullable)};`).join('\n')}
        };
      };`
  )
  .join('\n')}
    };
  };
}

export const createSupabaseClient = (supabaseUrl: string, supabaseAnonKey: string) => {
  return createClient<Database>(supabaseUrl, supabaseAnonKey);
};
`;

    return {
      providerId: 'supabase',
      providerName: 'Supabase',
      files: [
        {
          fileName: 'supabase_schema.sql',
          language: 'sql',
          content: sqlDdl,
          description: 'PostgreSQL DDL Migration mit Row Level Security (RLS) & Foreign Keys',
        },
        {
          fileName: 'supabaseClient.ts',
          language: 'typescript',
          content: tsClientCode,
          description: 'Typisierte TypeScript Interface Definitionen für @supabase/supabase-js',
        },
      ],
      notes: [
        'Kopieren Sie supabase_schema.sql direkt in den Supabase SQL Editor oder in /supabase/migrations.',
        'Alle RLS-Richtlinien sind standardmäßig auf "authenticated" Benutzer abgesichert.',
      ],
    };
  },
};

function mapToPgType(type: string, length?: number): string {
  const upper = (type || 'VARCHAR').toUpperCase();
  if (upper.includes('INT')) return 'BIGINT';
  if (upper.includes('DEC') || upper.includes('FLOA') || upper.includes('DOUB')) return 'NUMERIC(14,2)';
  if (upper.includes('BOOL')) return 'BOOLEAN';
  if (upper.includes('DATE')) return 'DATE';
  if (upper.includes('TIME')) return 'TIMESTAMP WITH TIME ZONE';
  if (upper.includes('BLOB') || upper.includes('BIN')) return 'BYTEA';
  return length ? `VARCHAR(${length})` : 'TEXT';
}

function mapToTsType(type: string, isNullable: boolean): string {
  const upper = (type || 'VARCHAR').toUpperCase();
  let base = 'string';
  if (upper.includes('INT') || upper.includes('DEC') || upper.includes('FLOA') || upper.includes('DOUB')) base = 'number';
  if (upper.includes('BOOL')) base = 'boolean';
  return isNullable ? `${base} | null` : base;
}
