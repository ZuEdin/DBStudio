/**
 * PocketBase BaaS Plugin
 * Generates pb_schema.json collections schema and JS/TS SDK integration.
 */

import { Table, Relationship } from '../../../types';
import { ICloudSyncProvider, CloudProviderExportResult } from '../../../types/cloudProvider';

export const PocketBasePlugin: ICloudSyncProvider = {
  id: 'pocketbase',
  name: 'PocketBase (Self-Hosted SQLite BaaS)',
  description: 'Generiert pb_schema.json für 1-Klick Import in PocketBase sowie typed PocketBase JS/TS SDK Helper.',
  category: 'baas',
  generateExport: (tables: Table[]) => {
    // Generate pb_schema.json collections
    const collections = tables.map((table, idx) => {
      const schemaFields = table.fields
        .filter((f) => !f.isPrimaryKey || f.name.toLowerCase() !== 'id') // PocketBase has auto 'id'
        .map((f) => {
          return {
            id: `field_${f.name}_${idx}`,
            name: f.name,
            type: mapToPbFieldType(f.type),
            required: !f.isNullable,
            presentable: f.type === 'VARCHAR',
            unique: false,
            options: f.type === 'VARCHAR' && f.length ? { max: f.length } : {},
          };
        });

      return {
        id: `col_${table.name.toLowerCase()}_${idx}`,
        name: table.name.toLowerCase().replace(/[^a-z0-9_]/g, '_'),
        type: 'base',
        system: false,
        schema: schemaFields,
        indexes: [],
        listRule: '@request.auth.id != ""',
        viewRule: '@request.auth.id != ""',
        createRule: '@request.auth.id != ""',
        updateRule: '@request.auth.id != ""',
        deleteRule: '@request.auth.id != ""',
        options: {},
      };
    });

    const pbSchemaJson = JSON.stringify(collections, null, 2);

    // TypeScript PocketBase SDK Helper
    let tsCode = `// PocketBase Client Helper generated by DB Studio Pro
import PocketBase from 'pocketbase';

export const pb = new PocketBase('http://127.0.0.1:8090');

// Typed Collection Names
export type AppCollections = ${tables.map((t) => `'${t.name.toLowerCase().replace(/[^a-z0-9_]/g, '_')}'`).join(' | ')};

// Helper for local offline or self-hosted connection
export async function authenticatePocketBase(email: string, pass: string) {
  return await pb.collection('users').authWithPassword(email, pass);
}
`;

    // Migration Guide
    let guideMd = `# PocketBase Migration & Import Guide

1. Starten Sie Ihre lokale PocketBase Instanz:
   \`\`\`bash
   ./pocketbase serve --http="127.0.0.1:8090"
   \`\`\`
2. Öffnen Sie das Admin-Dashboard unter:
   \`http://127.0.0.1:8090/_/\`
3. Navigieren Sie zu **Settings -> Sync & Import Collections** und laden Sie die Datei \`pb_schema.json\` hoch.
4. Fertig! Alle Tabellen, API-Routen und Validierungsregeln sind sofort einsatzbereit.
`;

    return {
      providerId: 'pocketbase',
      providerName: 'PocketBase',
      files: [
        {
          fileName: 'pb_schema.json',
          language: 'json',
          content: pbSchemaJson,
          description: 'PocketBase Collections & Rules Schema (Direkter Import im Admin UI)',
        },
        {
          fileName: 'pocketbaseClient.ts',
          language: 'typescript',
          content: tsCode,
          description: 'PocketBase SDK Initialisierung & TypeScript Typen',
        },
        {
          fileName: 'POCKETBASE_GUIDE.md',
          language: 'markdown',
          content: guideMd,
          description: 'Schritt-für-Schritt Anleitung zur Offline/Self-Hosted Bereitstellung',
        },
      ],
      notes: [
        'Vollständig offline-fähig mit der schlanken PocketBase Go-Binary (ca. 15 MB).',
        'Alle Collections sind standardmäßig per Auth-Token abgesichert.',
      ],
    };
  },
};

function mapToPbFieldType(type: string): string {
  const upper = (type || 'VARCHAR').toUpperCase();
  if (upper.includes('INT') || upper.includes('DEC') || upper.includes('FLOA') || upper.includes('DOUB')) return 'number';
  if (upper.includes('BOOL')) return 'bool';
  if (upper.includes('DATE') || upper.includes('TIME')) return 'date';
  if (upper.includes('BLOB') || upper.includes('BIN')) return 'file';
  if (upper.includes('JSON')) return 'json';
  return 'text';
}
