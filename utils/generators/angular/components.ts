
import { Table, Form, Report, VirtualFile, BackendConfig, Query } from '../../../types/index';
import { toCamelCase, toKebabCase, toPascalCase } from '../common';
import { generateHtmlForLayout } from './layoutHelper';

interface RouteInfo {
  path: string;
  component: string;
  folder: string;
  file: string;
}

export const generateAngularComponents = (tables: Table[], forms: Form[], reports: Report[], config: BackendConfig, appRoot: string, queries: Query[]): { files: VirtualFile[], routes: RouteInfo[] } => {
  const files: VirtualFile[] = [];
  const routes: RouteInfo[] = [];

  // Sidebar
  const navLinks = `
    <div class="px-4 py-2 text-xs font-bold text-slate-500 uppercase mt-4">Daten</div>
    ${tables.map(t => `<a routerLink="/${toCamelCase(t.name)}" routerLinkActive="bg-slate-700 text-white" class="block py-1 px-4 hover:bg-slate-700 text-slate-300 rounded mx-2 transition-colors">${t.name}</a>`).join('')}
    
    <div class="px-4 py-2 text-xs font-bold text-slate-500 uppercase mt-4">Formulare</div>
    ${forms.map(f => `<a routerLink="/forms/${toKebabCase(f.name)}/new" routerLinkActive="bg-slate-700 text-white" class="block py-1 px-4 hover:bg-slate-700 text-slate-300 rounded mx-2 transition-colors">${f.name}</a>`).join('')}
    
    <div class="px-4 py-2 text-xs font-bold text-slate-500 uppercase mt-4">Berichte</div>
    ${reports.map(r => `<a routerLink="/reports/${toKebabCase(r.name)}" routerLinkActive="bg-slate-700 text-white" class="block py-1 px-4 hover:bg-slate-700 text-slate-300 rounded mx-2 transition-colors">${r.name}</a>`).join('')}
  `;
  const sidebarHtml = `<aside class="w-64 bg-slate-800 text-white flex-shrink-0 flex flex-col h-screen"><div class="p-4 font-bold border-b border-slate-700 text-xl">${config.projectName}</div><nav class="py-2 flex-1 overflow-y-auto">${navLinks}</nav><div class="p-4 border-t border-slate-700 text-xs text-slate-500">Generated by DB Studio Pro</div></aside>`;
  const sidebarTs = `import { Component } from '@angular/core';
import { RouterLink, RouterLinkActive } from '@angular/router';

@Component({
  selector: 'app-sidebar',
  standalone: true,
  imports: [RouterLink, RouterLinkActive],
  templateUrl: './sidebar.component.html'
})
export class SidebarComponent {}`;
  files.push({ name: 'sidebar.component.html', path: `${appRoot}/components/sidebar/sidebar.component.html`, content: sidebarHtml, language: 'html' });
  files.push({ name: 'sidebar.component.ts', path: `${appRoot}/components/sidebar/sidebar.component.ts`, content: sidebarTs, language: 'typescript' });

  // App Component
  const appTs = `import { Component } from '@angular/core';
import { RouterOutlet } from '@angular/router';
import { SidebarComponent } from './components/sidebar/sidebar.component';

@Component({
  selector: 'app-root',
  standalone: true,
  imports: [RouterOutlet, SidebarComponent],
  templateUrl: './app.component.html'
})
export class AppComponent {}`;
  files.push({ name: 'app.component.html', path: `${appRoot}/app.component.html`, content: `<div class="flex min-h-screen bg-gray-50"><app-sidebar></app-sidebar><main class="flex-1 overflow-auto"><router-outlet></router-outlet></main></div>`, language: 'html' });
  files.push({ name: 'app.component.ts', path: `${appRoot}/app.component.ts`, content: appTs, language: 'typescript' });

  // Lists (Tables)
  tables.forEach(table => {
      const pascalName = toPascalCase(table.name);
      const kebabName = toKebabCase(pascalName);
      const camelName = toCamelCase(pascalName);
      const listCompName = `${pascalName}ListComponent`;
      
      const pkField = toCamelCase(table.fields.find(f => f.isPrimaryKey)?.name || 'id');
      const html = `<div class="p-6">
        <h1 class="text-2xl font-bold mb-4">${table.name}</h1>
        <a routerLink="/${camelName}/new" class="bg-blue-600 text-white px-4 py-2 rounded mb-4 inline-block">Neu erstellen</a>
        <div class="bg-white shadow rounded overflow-hidden">
            <table class="w-full text-left border-collapse">
                <thead class="bg-gray-100 border-b"><tr>${table.fields.map(f=>`<th class="p-3 font-semibold text-sm text-gray-600">${f.name}</th>`).join('')}<th class="p-3 font-semibold text-sm text-gray-600 text-right">Aktionen</th></tr></thead>
                <tbody>
                    <tr *ngFor="let item of items" class="border-b hover:bg-gray-50">
                        ${table.fields.map(f=>`<td class="p-3 text-sm text-gray-800">{{item.${toCamelCase(f.name)}}}</td>`).join('')}
                        <td class="p-3 text-right">
                            <button (click)="delete(item.${pkField})" class="text-red-600 hover:text-red-800 text-sm font-medium">Löschen</button>
                        </td>
                    </tr>
                </tbody>
            </table>
        </div>
      </div>`;
      
      const ts = `import { Component, OnInit } from '@angular/core';
import { CommonModule } from '@angular/common';
import { RouterLink } from '@angular/router';
import { ApiService } from '../../services/api.service';
import { ${pascalName} } from '../../models/${pascalName.toLowerCase()}.interface';

@Component({
  selector: 'app-${kebabName}-list',
  standalone: true,
  imports: [CommonModule, RouterLink],
  templateUrl: './${kebabName}-list.component.html'
})
export class ${listCompName} implements OnInit {
  items: ${pascalName}[] = [];

  constructor(private api: ApiService) {}

  ngOnInit() {
    this.load();
  }

  load() {
    this.api.getAll('${camelName}').subscribe(res => this.items = res);
  }

  delete(id: any) {
    if(confirm('Wirklich löschen?')) {
      this.api.delete('${camelName}', id).subscribe(() => this.load());
    }
  }
}`;
      files.push({ name: `${kebabName}-list.component.html`, path: `${appRoot}/pages/${kebabName}/${kebabName}-list.component.html`, content: html, language: 'html' });
      files.push({ name: `${kebabName}-list.component.ts`, path: `${appRoot}/pages/${kebabName}/${kebabName}-list.component.ts`, content: ts, language: 'typescript' });
      routes.push({ path: camelName, component: listCompName, folder: kebabName, file: `${kebabName}-list.component` });
  });

  // Forms
  forms.forEach(form => {
      const pascalName = toPascalCase(form.name);
      const formCompName = `${pascalName}FormComponent`;
      const kebabName = toKebabCase(pascalName) + '-form';
      
      const sourceTable = tables.find(t => t.id === form.sourceId);
      if (!sourceTable) return;
      
      const sourceTableModel = toPascalCase(sourceTable.name);
      const endpoint = toCamelCase(sourceTable.name);
      
      const lookups = [];
      const traverse = (el: any) => {
          if (el.widgetType === 'select' && el.lookup) lookups.push(el.lookup);
          if (el.children) el.children.forEach(traverse);
      };
      if (form.layout) traverse(form.layout);
      
      const lookupImports = [...new Map(lookups.map(l => {
          const t = tables.find(tbl => tbl.id === l.tableId);
          return t ? [toPascalCase(t.name), `import { ${toPascalCase(t.name)} } from '../../models/${toPascalCase(t.name).toLowerCase()}.interface';`] : null;
      }).filter(Boolean) as [string, string][]).values()].join('\n');
      
      const lookupProps = lookups.map(l => {
          const t = tables.find(tbl => tbl.id === l.tableId);
          return t ? `  ${toCamelCase(t.name)}List: ${toPascalCase(t.name)}[] = [];` : '';
      }).join('\n');
      
      const lookupLoads = lookups.map(l => {
          const t = tables.find(tbl => tbl.id === l.tableId);
          return t ? `    this.api.getAll('${toCamelCase(t.name)}').subscribe(res => this.${toCamelCase(t.name)}List = res);` : '';
      }).join('\n');

      const html = `<div class="p-6 max-w-4xl mx-auto">
        <div class="bg-white shadow rounded-lg p-6">
            <h1 class="text-2xl font-bold mb-6 pb-2 border-b">${form.name}</h1>
            <form (ngSubmit)="save()">
                ${form.layout ? generateHtmlForLayout(form.layout, tables) : '<p>Kein Layout</p>'}
                <div class="mt-6 flex justify-end">
                    <button type="submit" class="bg-blue-600 hover:bg-blue-700 text-white px-6 py-2 rounded font-medium transition-colors">Speichern</button>
                </div>
            </form>
        </div>
      </div>`;
      
      const ts = `import { Component, OnInit } from '@angular/core';
import { CommonModule } from '@angular/common';
import { FormsModule } from '@angular/forms';
import { ActivatedRoute, Router, RouterLink } from '@angular/router';
import { ApiService } from '../../services/api.service';
import { ${sourceTableModel} } from '../../models/${sourceTableModel.toLowerCase()}.interface';
${lookupImports}

@Component({
  selector: 'app-${kebabName}',
  standalone: true,
  imports: [CommonModule, FormsModule, RouterLink],
  templateUrl: './${kebabName}.component.html'
})
export class ${formCompName} implements OnInit {
  data: ${sourceTableModel} = {} as ${sourceTableModel};
${lookupProps}

  constructor(
    private api: ApiService, 
    private route: ActivatedRoute, 
    private router: Router
  ) {}

  ngOnInit() {
${lookupLoads}
    const id = this.route.snapshot.paramMap.get('id');
    if (id && id !== 'new') {
        this.api.getById('${endpoint}', id).subscribe(res => this.data = res);
    }
  }

  save() {
    const id = this.route.snapshot.paramMap.get('id');
    const operation = id && id !== 'new' 
      ? this.api.update('${endpoint}', id, this.data)
      : this.api.create('${endpoint}', this.data);
      
    operation.subscribe(() => this.router.navigate(['/${endpoint}']));
  }
}`;

      files.push({ name: `${kebabName}.component.html`, path: `${appRoot}/pages/forms/${kebabName}/${kebabName}.component.html`, content: html, language: 'html' });
      files.push({ name: `${kebabName}.component.ts`, path: `${appRoot}/pages/forms/${kebabName}/${kebabName}.component.ts`, content: ts, language: 'typescript' });
      routes.push({ path: `forms/${kebabName}/:id`, component: formCompName, folder: `forms/${kebabName}`, file: `${kebabName}.component` });
      routes.push({ path: `${endpoint}/:id`, component: formCompName, folder: `forms/${kebabName}`, file: `${kebabName}.component` });
  });

  // Reports
  reports.forEach(report => {
      const pascalName = toPascalCase(report.name);
      const reportCompName = `${pascalName}ReportComponent`;
      const kebabName = toKebabCase(pascalName) + '-report';
      
      let endpoint = 'unknown';
      let modelName = 'any';
      let modelImport = '';

      if (report.sourceType === 'table') {
          const t = tables.find(t => t.id === report.sourceId);
          if (t) {
              modelName = toPascalCase(t.name);
              endpoint = toCamelCase(modelName);
          }
      } else if (report.sourceType === 'query') {
          const q = queries.find(q => q.id === report.sourceId);
          if (q) {
              modelName = toPascalCase(q.name);
              endpoint = toCamelCase(modelName);
          }
      }

      if (modelName !== 'any') {
          modelImport = `import { ${modelName} } from '../../models/${modelName.toLowerCase()}.interface';`;
      }

      const columns = report.columns || [];
      
      const html = `<div class="p-8 bg-gray-50 min-h-full">
        <div class="bg-white shadow-lg p-10 max-w-5xl mx-auto">
            <h1 class="text-3xl font-bold mb-6 pb-2 border-b">${report.name}</h1>
            <div *ngIf="data.length === 0" class="text-gray-500 italic">Keine Daten verfügbar.</div>
            <table *ngIf="data.length > 0" class="w-full text-left border-collapse text-sm">
                <thead>
                    <tr class="border-b-2 border-black">
                        ${columns.map(c => `<th class="p-2 uppercase text-xs font-bold text-gray-600">${c.label}</th>`).join('')}
                    </tr>
                </thead>
                <tbody>
                    <tr *ngFor="let item of data" class="border-b hover:bg-gray-50">
                        ${columns.map(c => {
                            const fieldName = toCamelCase(c.label); 
                            return `<td class="p-2">{{ item['${fieldName}'] || item['${c.label}'] }}</td>`;
                        }).join('')}
                    </tr>
                </tbody>
            </table>
        </div>
      </div>`;
      
      const ts = `import { Component, OnInit } from '@angular/core';
import { CommonModule } from '@angular/common';
import { ApiService } from '../../services/api.service';
${modelImport}

@Component({
  selector: 'app-${kebabName}',
  standalone: true,
  imports: [CommonModule],
  templateUrl: './${kebabName}.component.html'
})
export class ${reportCompName} implements OnInit {
  data: ${modelName}[] = [];

  constructor(private api: ApiService) {}

  ngOnInit() {
      this.api.getAll('${endpoint}').subscribe(res => this.data = res);
  }
}`;
      
      files.push({ name: `${kebabName}.component.html`, path: `${appRoot}/pages/reports/${kebabName}/${kebabName}.component.html`, content: html, language: 'html' });
      files.push({ name: `${kebabName}.component.ts`, path: `${appRoot}/pages/reports/${kebabName}/${kebabName}.component.ts`, content: ts, language: 'typescript' });
      routes.push({ path: `reports/${kebabName}`, component: reportCompName, folder: `reports/${kebabName}`, file: `${kebabName}.component` });
  });

  return { files, routes };
};
