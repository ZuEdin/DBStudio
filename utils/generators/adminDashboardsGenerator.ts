/**
 * 1. Laravel Filament v3 Resource Generator
 * Generates Filament v3 Resource, Pages (List, Create, Edit), Form Schema & Table Columns/Filters
 */
export const generateFilamentV3ResourceProject = (
  tables: Table[],
  relationships: Relationship[] = []
): Record<string, string> => {
  const files: Record<string, string> = {};

  files['composer.json'] = JSON.stringify(
    {
      name: 'laravel/filament-v3-admin',
      type: 'project',
      description: 'Enterprise Laravel 11 & Filament v3 Admin Panel generated by DB Studio Pro',
      require: {
        php: '^8.3|^8.4',
        'laravel/framework': '^11.0',
        'filament/filament': '^3.2',
      },
      autoload: {
        'psr-4': {
          'App\\': 'app/',
          'Database\\Factories\\': 'database/factories/',
          'Database\\Seeders\\': 'database/seeders/',
        },
      },
    },
    null,
    2
  );

  tables.forEach((t) => {
    const tableName = t.name;
    const tableSlug = t.name.toLowerCase();

    // 1. Model
    const fillable = (t.fields || []).map((f) => `'${f.name}'`).join(', ');
    files[`app/Models/${tableName}.php`] = `<?php

namespace App\\Models;

use Illuminate\\Database\\Eloquent\\Factories\\HasFactory;
use Illuminate\\Database\\Eloquent\\Model;

class ${tableName} extends Model
{
    use HasFactory;

    protected $table = '${tableSlug}s';
    protected $fillable = [${fillable}];
}
`;

    // 2. Filament Resource Class
    const formComponents = (t.fields || [])
      .filter((f) => !f.isPrimaryKey)
      .map((f) => {
        const isRequired = f.allowNull === false || f.isNullable === false ? '->required()' : '->nullable()';
        let component = `Forms\\Components\\TextInput::make('${f.name}')`;

        if (f.type === 'BOOLEAN') {
          component = `Forms\\Components\\Toggle::make('${f.name}')`;
        } else if (f.type === 'DATE') {
          component = `Forms\\Components\\DatePicker::make('${f.name}')`;
        } else if (f.type === 'DATETIME' || f.type === 'TIMESTAMP') {
          component = `Forms\\Components\\DateTimePicker::make('${f.name}')`;
        } else if (f.type === 'TEXT') {
          component = `Forms\\Components\\Textarea::make('${f.name}')->rows(3)`;
        } else if (f.type === 'INTEGER' || f.type === 'DECIMAL' || f.type === 'FLOAT' || f.type === 'DOUBLE') {
          component = `Forms\\Components\\TextInput::make('${f.name}')->numeric()`;
        }

        return `                ${component}${isRequired}`;
      })
      .join(',\n');

    const tableColumns = (t.fields || [])
      .map((f) => {
        if (f.type === 'BOOLEAN') {
          return `                Tables\\Columns\\IconColumn::make('${f.name}')->boolean()`;
        }
        return `                Tables\\Columns\\TextColumn::make('${f.name}')->searchable()->sortable()`;
      })
      .join(',\n');

    const tableFilters = (t.fields || [])
      .filter((f) => f.type === 'BOOLEAN')
      .map((f) => `                Tables\\Filters\\TernaryFilter::make('${f.name}')`)
      .join(',\n');

    files[`app/Filament/Resources/${tableName}Resource.php`] = `<?php

namespace App\\Filament\\Resources;

use App\\Filament\\Resources\\${tableName}Resource\\Pages;
use App\\Models\\${tableName};
use Filament\\Forms;
use Filament\\Forms\\Form;
use Filament\\Resources\\Resource;
use Filament\\Tables;
use Filament\\Tables\\Table;

class ${tableName}Resource extends Resource
{
    protected static ?string $model = ${tableName}::class;
    protected static ?string $navigationIcon = 'heroicon-o-rectangle-stack';
    protected static ?string $navigationGroup = 'Datenverwaltung';

    public static function form(Form $form): Form
    {
        return $form
            ->schema([
${formComponents}
            ]);
    }

    public static function table(Table $table): Table
    {
        return $table
            ->columns([
${tableColumns}
            ])
            ->filters([
${tableFilters}
            ])
            ->actions([
                Tables\\Actions\\EditAction::make(),
                Tables\\Actions\\DeleteAction::make(),
            ])
            ->bulkActions([
                Tables\\Actions\\BulkActionGroup::make([
                    Tables\\Actions\\DeleteBulkAction::make(),
                ]),
            ]);
    }

    public static function getPages(): array
    {
        return [
            'index' => Pages\\List${tableName}s::route('/'),
            'create' => Pages\\Create${tableName}::route('/create'),
            'edit' => Pages\\Edit${tableName}::route('/{record}/edit'),
        ];
    }
}
`;

    // Pages: List, Create, Edit
    files[`app/Filament/Resources/${tableName}Resource/Pages/List${tableName}s.php`] = `<?php

namespace App\\Filament\\Resources\\${tableName}Resource\\Pages;

use App\\Filament\\Resources\\${tableName}Resource;
use Filament\\Actions;
use Filament\\Resources\\Pages\\ListRecords;

class List${tableName}s extends ListRecords
{
    protected static string $resource = ${tableName}Resource::class;

    protected function getHeaderActions(): array
    {
        return [
            Actions\\CreateAction::make(),
        ];
    }
}
`;

    files[`app/Filament/Resources/${tableName}Resource/Pages/Create${tableName}.php`] = `<?php

namespace App\\Filament\\Resources\\${tableName}Resource\\Pages;

use App\\Filament\\Resources\\${tableName}Resource;
use Filament\\Resources\\Pages\\CreateRecord;

class Create${tableName} extends CreateRecord
{
    protected static string $resource = ${tableName}Resource::class;
}
`;

    files[`app/Filament/Resources/${tableName}Resource/Pages/Edit${tableName}.php`] = `<?php

namespace App\\Filament\\Resources\\${tableName}Resource\\Pages;

use App\\Filament\\Resources\\${tableName}Resource;
use Filament\\Actions;
use Filament\\Resources\\Pages\\EditRecord;

class Edit${tableName} extends EditRecord
{
    protected static string $resource = ${tableName}Resource::class;

    protected function getHeaderActions(): array
    {
        return [
            Actions\\DeleteAction::make(),
        ];
    }
}
`;
  });

  return files;
};

/**
 * 2. Next.js 15 & Refine Admin-Panel Boilerplate Generator
 */
export const generateNextjsRefineAdminProject = (
  tables: Table[],
  relationships: Relationship[] = []
): Record<string, string> => {
  const files: Record<string, string> = {};

  files['package.json'] = JSON.stringify(
    {
      name: 'nextjs15-refine-admin',
      version: '1.0.0',
      private: true,
      scripts: {
        dev: 'next dev',
        build: 'next build',
        start: 'next start',
      },
      dependencies: {
        next: '^15.0.0',
        react: '^19.0.0',
        'react-dom': '^19.0.0',
        '@refinedev/core': '^4.50.0',
        '@refinedev/nextjs-router': '^6.0.0',
        '@tanstack/react-table': '^8.20.0',
        zod: '^3.23.0',
        'lucide-react': '^0.450.0',
        tailwindcss: '^4.0.0',
        clsx: '^2.1.0',
      },
    },
    null,
    2
  );

  // App Layout
  files['app/layout.tsx'] = `import React from 'react';
import './globals.css';

export const metadata = {
  title: 'Next.js 15 Refine Admin Dashboard',
  description: 'Enterprise Admin Panel generated by DB Studio Pro',
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="de">
      <body className="bg-slate-100 text-slate-900 font-sans antialiased">
        <div className="min-h-screen flex">
          {children}
        </div>
      </body>
    </html>
  );
}
`;

  files['app/globals.css'] = `@import "tailwindcss";`;

  // Main Admin Page
  files['app/admin/page.tsx'] = `import React from 'react';
import Link from 'next/link';

export default function AdminDashboardPage() {
  return (
    <div className="p-8 max-w-5xl mx-auto space-y-6">
      <h1 className="text-3xl font-extrabold text-slate-900">Admin Dashboard (Next.js 15 + Refine)</h1>
      <p className="text-slate-600">Verwalten Sie Ihre Tabellen und Ressourcen mit automatischem Zod-Validierungs-Binding.</p>
      
      <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
        ${tables
          .map(
            (t) => `<div key="${t.id}" className="p-5 bg-white border border-slate-200 rounded-xl shadow-xs hover:border-blue-500 transition">
          <h3 className="font-bold text-lg text-slate-800">${t.name}</h3>
          <p className="text-xs text-slate-500 mb-4">${t.fields?.length || 0} Felder konfiguriert</p>
          <Link href="/admin/${t.name.toLowerCase()}" className="inline-block px-3 py-1.5 bg-blue-600 text-white font-bold text-xs rounded hover:bg-blue-700">
            Ressource öffnen &rarr;
          </Link>
        </div>`
          )
          .join('\n        ')}
      </div>
    </div>
  );
}
`;

  // Resource Zod Schemas & API Actions
  tables.forEach((t) => {
    const tableSlug = t.name.toLowerCase();

    // Zod Schema
    const zodFields = (t.fields || [])
      .map((f) => {
        let zType = 'z.string()';
        if (f.type === 'INTEGER' || f.type === 'DECIMAL' || f.type === 'FLOAT') zType = 'z.number()';
        if (f.type === 'BOOLEAN') zType = 'z.boolean()';

        if (f.allowNull !== false && f.isNullable !== false) {
          zType += '.optional()';
        }
        return `  ${f.name}: ${zType},`;
      })
      .join('\n');

    files[`lib/schemas/${tableSlug}.ts`] = `import { z } from 'zod';

export const ${t.name}Schema = z.object({
${zodFields}
});

export type ${t.name}Input = z.infer<typeof ${t.name}Schema>;
`;

    // Next.js Server Action API Route
    files[`app/api/admin/${tableSlug}/route.ts`] = `import { NextResponse } from 'next/server';
import { ${t.name}Schema } from '@/lib/schemas/${tableSlug}';

export async function GET() {
  return NextResponse.json({
    data: [],
    total: 0,
    message: 'Next.js 15 Server Action placeholder for ${t.name}',
  });
}

export async function POST(request: Request) {
  try {
    const body = await request.json();
    const validated = ${t.name}Schema.parse(body);
    return NextResponse.json({ success: true, data: validated });
  } catch (err: any) {
    return NextResponse.json({ error: err.errors || 'Validation error' }, { status: 400 });
  }
}
`;
  });

  return files;
};

/**
 * 3. Supabase & PocketBase Bootstrap Generator
 */
export const generateSupabasePocketbaseBootstrap = (
  tables: Table[],
  relationships: Relationship[] = []
): Record<string, string> => {
  const files: Record<string, string> = {};

  // 1. Supabase SQL Migration with RLS
  let supabaseSql = `-- Supabase Initial Schema & RLS Migration
-- Generated by DB Studio Pro

`;

  tables.forEach((t) => {
    const tableName = t.name.toLowerCase();
    const columns = (t.fields || [])
      .map((f) => {
        let sqlType = 'VARCHAR(255)';
        if (f.isPrimaryKey) sqlType = 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
        else if (f.type === 'INTEGER') sqlType = 'INTEGER';
        else if (f.type === 'BIGINT') sqlType = 'BIGINT';
        else if (f.type === 'DECIMAL' || f.type === 'FLOAT') sqlType = 'NUMERIC(12, 2)';
        else if (f.type === 'BOOLEAN') sqlType = 'BOOLEAN DEFAULT FALSE';
        else if (f.type === 'DATE') sqlType = 'DATE';
        else if (f.type === 'DATETIME' || f.type === 'TIMESTAMP') sqlType = 'TIMESTAMPTZ DEFAULT NOW()';
        else if (f.type === 'TEXT') sqlType = 'TEXT';
        else if (f.type === 'JSON') sqlType = 'JSONB';

        const nullability = f.allowNull === false || f.isNullable === false ? ' NOT NULL' : '';
        return `  "${f.name}" ${sqlType}${nullability}`;
      })
      .join(',\n');

    supabaseSql += `CREATE TABLE IF NOT EXISTS public."${tableName}" (\n${columns}\n);\n\n`;
    supabaseSql += `-- Enable Row Level Security (RLS)\n`;
    supabaseSql += `ALTER TABLE public."${tableName}" ENABLE ROW LEVEL SECURITY;\n\n`;
    supabaseSql += `-- RLS Policy: Authenticated Read/Write Access\n`;
    supabaseSql += `CREATE POLICY "Allow authenticated access to ${tableName}"\n`;
    supabaseSql += `  ON public."${tableName}"\n`;
    supabaseSql += `  FOR ALL\n`;
    supabaseSql += `  TO authenticated\n`;
    supabaseSql += `  USING (true)\n`;
    supabaseSql += `  WITH CHECK (true);\n\n`;
  });

  files['supabase/migrations/001_initial_schema.sql'] = supabaseSql;

  // Supabase Client Helper
  files['src/lib/supabaseClient.ts'] = `import { createClient } from '@supabase/supabase-js';

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL || 'https://xyzcompany.supabase.co';
const supabaseAnonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || 'public-anon-key';

export const supabase = createClient(supabaseUrl, supabaseAnonKey);
`;

  // 2. PocketBase Schema JSON Import
  const pbCollections = tables.map((t) => {
    const tableName = t.name.toLowerCase();
    const pbFields = (t.fields || []).map((f) => {
      let pbType = 'text';
      if (f.type === 'INTEGER' || f.type === 'DECIMAL') pbType = 'number';
      if (f.type === 'BOOLEAN') pbType = 'bool';
      if (f.type === 'DATE' || f.type === 'DATETIME') pbType = 'date';
      if (f.type === 'JSON') pbType = 'json';

      return {
        id: `f_${f.name.toLowerCase()}`,
        name: f.name.toLowerCase(),
        type: pbType,
        required: f.allowNull === false || f.isNullable === false,
        unique: Boolean(f.isUnique),
      };
    });

    return {
      id: `col_${tableName}`,
      name: tableName,
      type: 'base',
      system: false,
      schema: pbFields,
      listRule: '@request.auth.id != ""',
      viewRule: '@request.auth.id != ""',
      createRule: '@request.auth.id != ""',
      updateRule: '@request.auth.id != ""',
      deleteRule: '@request.auth.id != ""',
    };
  });

  files['pocketbase/pb_schema.json'] = JSON.stringify(pbCollections, null, 2);

  files['src/lib/pocketbaseClient.ts'] = `import PocketBase from 'pocketbase';

export const pb = new PocketBase(process.env.NEXT_PUBLIC_POCKETBASE_URL || 'http://127.0.0.1:8090');
`;

  return files;
};
