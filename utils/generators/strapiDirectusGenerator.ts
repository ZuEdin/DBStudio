import { Table, Relationship } from '../../types';

export interface HeadlessCmsOptions {
  cmsType?: 'STRAPI_V5' | 'DIRECTUS_10' | 'BOTH';
  projectName?: string;
  enableRbac?: boolean;
  enableDraftAndPublish?: boolean;
}

export const generateStrapiV5Project = (
  tables: Table[],
  relationships: Relationship[] = [],
  options: HeadlessCmsOptions = {}
): Record<string, string> => {
  const files: Record<string, string> = {};
  const projectName = (options.projectName || 'StrapiApp').toLowerCase().replace(/[^a-z0-9_-]/g, '');

  // 1. package.json for Strapi v5
  files['package.json'] = JSON.stringify(
    {
      name: projectName,
      private: true,
      version: '1.0.0',
      description: 'Enterprise Strapi v5 Headless CMS generated by DB Studio Pro',
      scripts: {
        develop: 'strapi develop',
        start: 'strapi start',
        build: 'strapi build',
        strapi: 'strapi',
      },
      dependencies: {
        '@strapi/strapi': '^5.0.0',
        '@strapi/plugin-users-permissions': '^5.0.0',
        '@strapi/plugin-cloud': '^5.0.0',
        better_sqlite3: '^11.0.0',
      },
      engines: {
        node: '>=18.0.0 <=22.x.x',
        npm: '>=6.0.0',
      },
    },
    null,
    2
  );

  // 2. Strapi Config Files
  files['config/server.js'] = `module.exports = ({ env }) => ({
  host: env('HOST', '0.0.0.0'),
  port: env.int('PORT', 1337),
  app: {
    keys: env.array('APP_KEYS', ['key1', 'key2']),
  },
});`;

  files['config/database.js'] = `module.exports = ({ env }) => ({
  connection: {
    client: 'sqlite',
    connection: {
      filename: env('DATABASE_FILENAME', '.tmp/data.db'),
    },
    useNullAsDefault: true,
  },
});`;

  // 3. Generate Strapi Content-Types for each Table
  tables.forEach((t) => {
    const tableSlug = t.name.toLowerCase().replace(/[^a-z0-9]/g, '');
    const singularName = tableSlug;
    const pluralName = `${tableSlug}s`;

    const attributes: Record<string, any> = {};

    (t.fields || []).forEach((f) => {
      if (f.isPrimaryKey && f.type === 'INTEGER') return; // Strapi handles auto id

      let attrType = 'string';
      if (f.type === 'INTEGER' || f.type === 'BIGINT') attrType = 'integer';
      else if (f.type === 'DECIMAL' || f.type === 'FLOAT' || f.type === 'DOUBLE') attrType = 'decimal';
      else if (f.type === 'BOOLEAN') attrType = 'boolean';
      else if (f.type === 'DATE') attrType = 'date';
      else if (f.type === 'DATETIME' || f.type === 'TIMESTAMP') attrType = 'datetime';
      else if (f.type === 'TEXT') attrType = 'text';
      else if (f.type === 'JSON') attrType = 'json';

      attributes[f.name.toLowerCase()] = {
        type: attrType,
        required: Boolean(f.allowNull === false || f.isNullable === false),
        unique: Boolean(f.isUnique),
      };
    });

    // Process relationships
    relationships
      .filter((r) => r.fromTableId === t.id || r.toTableId === t.id)
      .forEach((r) => {
        const isSource = r.fromTableId === t.id;
        const targetTable = tables.find((tbl) => tbl.id === (isSource ? r.toTableId : r.fromTableId));
        if (targetTable) {
          const targetSlug = targetTable.name.toLowerCase().replace(/[^a-z0-9]/g, '');
          const relName = targetSlug;
          attributes[relName] = {
            type: 'relation',
            relation: (r.type === '1:n' || r.type === '1:N') ? (isSource ? 'manyToOne' : 'oneToMany') : 'manyToMany',
            target: `api::${targetSlug}.${targetSlug}`,
          };
        }
      });

    const schemaObj = {
      kind: 'collectionType',
      collectionName: pluralName,
      info: {
        singularName: singularName,
        pluralName: pluralName,
        displayName: t.name,
        description: `Content Type for ${t.name} generated by DB Studio Pro`,
      },
      options: {
        draftAndPublish: options.enableDraftAndPublish !== false,
      },
      pluginOptions: {},
      attributes: attributes,
    };

    // Schema JSON
    files[`src/api/${tableSlug}/content-types/${tableSlug}/schema.json`] = JSON.stringify(schemaObj, null, 2);

    // Controller
    files[`src/api/${tableSlug}/controllers/${tableSlug}.ts`] = `import { factories } from '@strapi/strapi';

export default factories.createCoreController('api::${tableSlug}.${tableSlug}');
`;

    // Service
    files[`src/api/${tableSlug}/services/${tableSlug}.ts`] = `import { factories } from '@strapi/strapi';

export default factories.createCoreService('api::${tableSlug}.${tableSlug}');
`;

    // Router
    files[`src/api/${tableSlug}/routes/${tableSlug}.ts`] = `import { factories } from '@strapi/strapi';

export default factories.createCoreRouter('api::${tableSlug}.${tableSlug}');
`;
  });

  // 4. RBAC Permissions Preset
  files['config/permissions.json'] = JSON.stringify(
    {
      roles: {
        authenticated: {
          name: 'Authenticated',
          description: 'Default role for authenticated users',
          permissions: tables.map((t) => {
            const tableSlug = t.name.toLowerCase().replace(/[^a-z0-9]/g, '');
            return {
              action: `api::${tableSlug}.${tableSlug}.find`,
              subject: null,
            };
          }),
        },
        public: {
          name: 'Public',
          description: 'Default role for unauthenticated users',
          permissions: tables.map((t) => {
            const tableSlug = t.name.toLowerCase().replace(/[^a-z0-9]/g, '');
            return {
              action: `api::${tableSlug}.${tableSlug}.find`,
              subject: null,
            };
          }),
        },
      },
    },
    null,
    2
  );

  return files;
};

export const generateDirectusProject = (
  tables: Table[],
  relationships: Relationship[] = [],
  options: HeadlessCmsOptions = {}
): Record<string, string> => {
  const files: Record<string, string> = {};

  const collections: any[] = [];
  const fields: any[] = [];
  const directusRelations: any[] = [];

  tables.forEach((t) => {
    const tableName = t.name.toLowerCase().replace(/[^a-z0-9_]/g, '');

    collections.push({
      collection: tableName,
      icon: 'storage',
      note: `Collection for ${t.name} generated by DB Studio Pro`,
      display_template: '{{id}}',
      hidden: false,
      singleton: false,
      translations: [
        {
          language: 'de-DE',
          translation: t.name,
        },
      ],
    });

    (t.fields || []).forEach((f) => {
      let fieldType = 'string';
      let interfaceName = 'input';

      if (f.type === 'INTEGER' || f.type === 'BIGINT') {
        fieldType = 'integer';
        interfaceName = 'input';
      } else if (f.type === 'DECIMAL' || f.type === 'FLOAT' || f.type === 'DOUBLE') {
        fieldType = 'float';
        interfaceName = 'input';
      } else if (f.type === 'BOOLEAN') {
        fieldType = 'boolean';
        interfaceName = 'boolean';
      } else if (f.type === 'DATE' || f.type === 'DATETIME' || f.type === 'TIMESTAMP') {
        fieldType = 'dateTime';
        interfaceName = 'datetime';
      } else if (f.type === 'TEXT') {
        fieldType = 'text';
        interfaceName = 'input-multiline';
      }

      fields.push({
        collection: tableName,
        field: f.name.toLowerCase(),
        type: fieldType,
        meta: {
          interface: interfaceName,
          options: {},
          display: null,
          required: Boolean(f.allowNull === false || f.isNullable === false),
          readonly: false,
          hidden: false,
          width: 'full',
          translations: [
            {
              language: 'de-DE',
              translation: f.name,
            },
          ],
        },
        schema: {
          is_primary_key: Boolean(f.isPrimaryKey),
          is_nullable: Boolean(f.allowNull !== false && f.isNullable !== false),
          is_unique: Boolean(f.isUnique),
        },
      });
    });
  });

  // Process relationships into Directus format
  relationships.forEach((r, idx) => {
    const srcTable = tables.find((tbl) => tbl.id === r.fromTableId);
    const tgtTable = tables.find((tbl) => tbl.id === r.toTableId);
    if (srcTable && tgtTable) {
      directusRelations.push({
        id: idx + 1,
        many_collection: srcTable.name.toLowerCase(),
        many_field: r.fromFieldId ? 'fk_field' : 'parent_id',
        one_collection: tgtTable.name.toLowerCase(),
        one_field: null,
      });
    }
  });

  const snapshot = {
    version: 1,
    directus: '10.10.0',
    collections,
    fields,
    relations: directusRelations,
  };

  files['directus-schema-snapshot.json'] = JSON.stringify(snapshot, null, 2);

  files['docker-compose.yml'] = `version: '3.8'
services:
  directus:
    image: directus/directus:10.10.0
    ports:
      - '8055:8055'
    environment:
      KEY: 'db-studio-pro-directus-key'
      SECRET: 'db-studio-pro-directus-secret'
      ADMIN_EMAIL: 'admin@example.com'
      ADMIN_PASSWORD: 'dbs-password-123'
      DB_CLIENT: 'sqlite3'
      DB_FILENAME: './data/data.db'
    volumes:
      - ./data:/directus/database
      - ./uploads:/directus/uploads
`;

  files['README.md'] = `# Directus 10 Schema Snapshot
Importieren Sie \`directus-schema-snapshot.json\` direkt über das Directus CLI oder Admin Panel:

\`\`\`bash
npx directus schema apply ./directus-schema-snapshot.json
\`\`\`
`;

  return files;
};
