
import { Table, Relationship, Query, BackendConfig, VirtualFile, Form, Report } from '../../types/index';
import { generateReact } from './reactGenerator';
import { generateNodeJs } from './nodeGenerator';
import i18n from '../../i18n';

export const generateElectron = (tables: Table[], relationships: Relationship[], queries: Query[], config: BackendConfig, forms: Form[], reports: Report[]): VirtualFile[] => {
  const root = `ElectronApp`;
  const files: VirtualFile[] = [];
  
  // Defensive checks to ensure arrays are defined
  const safeTables = tables || [];
  const safeRelationships = relationships || [];
  const safeQueries = queries || [];
  const safeForms = forms || [];
  const safeReports = reports || [];
  
  // Default Settings
  const settings = config.electronSettings || { includeBackend: true, bundleFrontend: true };
  const { includeBackend, bundleFrontend, targetUrl } = settings;
  const bePort = config.port || 3001;
  const fePort = config.frontendPort || 3000;

  // --- 1. Frontend Generation (Folder: Projektname_Frontend) ---
  if (bundleFrontend) {
      const reactFiles = generateReact(safeTables, safeRelationships, safeQueries, config, safeForms, safeReports);
      
      if (Array.isArray(reactFiles)) {
          reactFiles.forEach(f => {
              // Anpassung: Pfad verschieben nach /Frontend
              // Entferne das ursprüngliche 'Frontend/' Präfix vom React Generator, falls vorhanden, und setze neues
              let relativePath = f.path.replace(/^Frontend\//, '');
              
              // Vite Config: Base Path für Electron anpassen (relative Pfade)
              if (f.name === 'vite.config.ts') {
                  f.content = `import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import path from 'path';

export default defineConfig({
  plugins: [react()],
  base: './', // Wichtig für Electron: Relative Pfade für Assets
  build: {
    outDir: 'dist',
    emptyOutDir: true
  },
  server: {
    port: ${fePort}
  },
  resolve: {
    alias: {
      "@": path.resolve(__dirname, "./src"),
    },
  },
});`;
              }

              // API Config: Auf fixen Port des integrierten Backends zeigen
              if (f.name === 'api.ts' && includeBackend) {
                  f.content = f.content.replace(
                      /const API_URL = .*/, 
                      `const API_URL = 'http://localhost:${bePort}/api';` 
                  );
              }

              f.path = `${root}/Frontend/${relativePath}`;
              files.push(f);
          });
      }
  }

  // --- 2. Backend Generation (Folder: Projektname_Backend) ---
  if (includeBackend) {
      const nodeFiles = generateNodeJs(safeTables, safeRelationships, safeQueries, config);
      
      if (Array.isArray(nodeFiles)) {
          nodeFiles.forEach(f => {
              // Entferne das ursprüngliche 'Backend/Projektname' Präfix
              let relativePath = f.path.replace(`Backend/${config.projectName}/`, '');
              
              // README im Backend brauchen wir nicht unbedingt im Root, aber im Backend Ordner ok
              if (f.name === 'README.md') return; 

              f.path = `${root}/Backend/${relativePath}`;
              files.push(f);
          });
      }
  }

  // --- 3. Root Package.json (Orchestrator) ---
  const scripts: any = {
      "start": "electron .",
      "electron": "electron .",
      "electron:dev": `cross-env USE_DEV_SERVER=true wait-on tcp:${fePort} tcp:${bePort} && electron .`,
      "dev": "concurrently -k \"npm run backend\" \"npm run frontend\" \"npm run electron:dev\"",
      "build:frontend": "cd Frontend && npm run build",
      "build": "cd Frontend && npm run build && cd .. && electron-builder",
      "dist": "npm run build",
      "install-all": "npm install && cd Frontend && npm install && cd ../Backend && npm install"
  };

  if (includeBackend) {
      scripts["backend"] = "cd Backend && node server.js";
  } else {
      scripts["backend"] = "echo 'No Backend'";
  }

  if (bundleFrontend) {
      scripts["frontend"] = "cd Frontend && npm run dev";
  } else {
      scripts["frontend"] = "echo 'No Frontend'";
  }

  const packageJson = {
    name: `${config.projectName.toLowerCase()}-desktop`,
    version: "1.0.0",
    description: "Generated by DB Studio Pro",
    main: "main.js",
    scripts: scripts,
    devDependencies: {
      "electron": "^33.3.0",
      "electron-builder": "^25.1.8",
      "concurrently": "^9.1.0",
      "cross-env": "^7.0.3",
      "wait-on": "^8.0.1",
      "electron-is-dev": "^3.0.1"
    },
    build: {
      "appId": `com.example.${config.projectName.toLowerCase()}`,
      "productName": config.projectName,
      "files": [
        "Frontend/dist/**/*", 
        "Backend/**/*",
        "main.js",
        "preload.js",
        "package.json"
      ],
      "directories": {
        "output": "release"
      },
      "extraResources": [
          // Falls Datenbank-Dateien (SQLite) mitkopiert werden müssen, hier definieren
          // { "from": "Backend/database.sqlite", "to": "database.sqlite" }
      ]
    }
  };

  files.push({
      name: 'package.json',
      path: `${root}/package.json`,
      content: JSON.stringify(packageJson, null, 2),
      language: 'json'
  });

  // --- 4. Electron Main Process (main.js) ---
  let backendLogic = '';
  if (includeBackend) {
      backendLogic = `
// --- BACKEND STARTUP ---
let apiProcess;

function startApiServer() {
  const apiPath = path.join(__dirname, 'Backend', 'server.js');
  console.log('Starte Backend-Server:', apiPath);

  apiProcess = fork(apiPath, [], {
    env: { 
      ...process.env, 
      PORT: ${bePort}, // Fixer Port für interne Kommunikation
      NODE_ENV: 'production'
    },
    stdio: 'inherit'
  });
}

app.on('will-quit', () => {
  if (apiProcess) {
      console.log('Beende Backend...');
      apiProcess.kill();
  }
});
// -----------------------
`;
  }

  const mainJsContent = `const { app, BrowserWindow, ipcMain, shell } = require('electron');
const path = require('path');
const fs = require('fs');
const { fork, execSync } = require('child_process');

let mainWindow;

// Frontend automatisch transpilieren/bauen falls Frontend/dist/index.html nicht existiert
function ensureFrontendBuilt() {
  if (!${bundleFrontend ? 'true' : 'false'}) return;
  const distIndex = path.join(__dirname, 'Frontend', 'dist', 'index.html');
  if (!fs.existsSync(distIndex)) {
    console.log('Frontend dist nicht gefunden. Transpiliere Frontend...');
    try {
      execSync('npm run build', { cwd: path.join(__dirname, 'Frontend'), stdio: 'inherit' });
      console.log('Frontend erfolgreich transpiliert.');
    } catch (err) {
      console.error('Fehler beim Transpilieren des Frontends:', err);
    }
  }
}

${backendLogic}

function createWindow() {
  mainWindow = new BrowserWindow({
    width: 1280,
    height: 900,
    webPreferences: {
      preload: path.join(__dirname, 'preload.js'),
      nodeIntegration: false,
      contextIsolation: true,
    },
    autoHideMenuBar: false,
    title: "${config.projectName}"
  });

  const useDevServer = process.env.USE_DEV_SERVER === 'true';
  if (useDevServer) {
    // Entwicklungsmodus mit Hot Reloading
    mainWindow.loadURL('http://localhost:${fePort}');
    mainWindow.webContents.openDevTools();
  } else {
    // Normaler Desktop-Start (transpiliert falls noetig und laedt lokales HTML)
    ensureFrontendBuilt();
    mainWindow.loadFile(path.join(__dirname, 'Frontend', 'dist', 'index.html'));
  }

  // Externe Links im Browser öffnen
  mainWindow.webContents.setWindowOpenHandler(({ url }) => {
      if (url.startsWith('http')) {
          shell.openExternal(url);
          return { action: 'deny' };
      }
      return { action: 'allow' };
  });
}

app.whenReady().then(() => {
  ${includeBackend ? 'startApiServer();' : ''}
  createWindow();

  app.on('activate', () => {
    if (BrowserWindow.getAllWindows().length === 0) createWindow();
  });
});

app.on('window-all-closed', () => {
  if (process.platform !== 'darwin') app.quit();
});
`;

  files.push({ name: 'main.js', path: `${root}/main.js`, content: mainJsContent, language: 'javascript' });

  // --- 5. Preload Script ---
  files.push({ name: 'preload.js', path: `${root}/preload.js`, content: `const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('electronAPI', {
  send: (channel, data) => ipcRenderer.send(channel, data),
  on: (channel, func) => ipcRenderer.on(channel, (event, ...args) => func(...args))
});`, language: 'javascript' });

  // --- 6. run.bat (Das Menü) - Localized ---
  const batContent = `@echo off
title ${config.projectName} Manager
cls

:MENU
cls
echo =================================================
echo   ${config.projectName} - ${i18n.t('generator.bat_menu')}
echo =================================================
echo.
echo  [1] ${i18n.t('generator.bat_install')}
echo  [2] Electron App starten (electron .)
echo  [3] Dev-Modus mit Live-Reload (${i18n.t('generator.bat_dev')})
echo  [4] ${i18n.t('generator.bat_build')}
echo  [5] ${i18n.t('generator.bat_exit')}
echo.
set /p choice="${i18n.t('generator.bat_choice')} (1-5): "

if "%choice%"=="1" goto INSTALL
if "%choice%"=="2" goto START
if "%choice%"=="3" goto DEV
if "%choice%"=="4" goto BUILD
if "%choice%"=="5" exit

goto MENU

:INSTALL
cls
echo Installiere Root Dependencies...
call npm install
echo.
echo Installiere Backend Dependencies...
cd Backend
call npm install
cd ..
echo.
echo Installiere Frontend Dependencies...
cd Frontend
call npm install
cd ..
echo.
echo Fertig! Druecke eine Taste...
pause
goto MENU

:START
cls
echo Starte Electron App...
echo Backend Port: ${bePort}
call npm start
pause
goto MENU

:DEV
cls
echo Starte Development Environment mit Live-Reload...
echo Backend Port: ${bePort}
echo Frontend Port: ${fePort}
call npm run dev
pause
goto MENU

:BUILD
cls
echo Baue Frontend...
cd Frontend
call npm run build
cd ..
echo.
echo Erstelle Desktop App (Electron Builder)...
call npm run dist
echo.
echo Build abgeschlossen! Siehe 'release' Ordner.
pause
goto MENU
`;

  files.push({ name: 'run.bat', path: `${root}/run.bat`, content: batContent, language: 'text' });

  // --- 6b. run.sh (Interactive Menu for macOS/Linux) ---
  const shContent = `#!/bin/bash
# ${config.projectName} Desktop App Manager (macOS/Linux)

show_menu() {
  clear
  echo "================================================="
  echo "  ${config.projectName} - App Manager"
  echo "================================================="
  echo ""
  echo "  [1] Dependencies installieren (npm install)"
  echo "  [2] Electron App starten (electron .)"
  echo "  [3] Dev-Modus mit Live-Reload"
  echo "  [4] Desktop App bauen (electron-builder)"
  echo "  [5] Beenden"
  echo ""
  read -p "Auswahl (1-5): " choice
  case $choice in
    1) install_deps ;;
    2) start_app ;;
    3) start_dev ;;
    4) build_app ;;
    5) exit 0 ;;
    *) show_menu ;;
  esac
}

install_deps() {
  clear
  echo "Installiere Root Dependencies..."
  npm install
  echo ""
  echo "Installiere Backend Dependencies..."
  cd Backend && npm install && cd ..
  echo ""
  echo "Installiere Frontend Dependencies..."
  cd Frontend && npm install && cd ..
  echo ""
  echo "Fertig! Beliebige Taste druecken zum Zurueckkehren..."
  read -n 1 -s
  show_menu
}

start_app() {
  clear
  echo "Starte Electron App..."
  echo "Backend Port: ${bePort}"
  npm start
  read -n 1 -s
  show_menu
}

start_dev() {
  clear
  echo "Starte Development Environment..."
  echo "Backend Port: ${bePort}"
  echo "Frontend Port: ${fePort}"
  npm run dev
  read -n 1 -s
  show_menu
}

build_app() {
  clear
  echo "Baue Frontend..."
  cd Frontend && npm run build && cd ..
  echo ""
  echo "Erstelle Desktop App (Electron Builder)..."
  npm run dist
  echo ""
  echo "Build abgeschlossen! Siehe 'release' Ordner."
  read -n 1 -s
  show_menu
}

# Start the menu
show_menu
`;
  files.push({ name: 'run.sh', path: `${root}/run.sh`, content: shContent, language: 'text' });

  // --- 7. Documentation - Localized ---
  const readmeContent = `# ${config.projectName} Desktop App

## ${i18n.t('generator.structure')}

- **Backend/**: Node.js Express API Server (unterstuetzt SQLite, MySQL, PostgreSQL, MSSQL).
- **Frontend/**: React / Vite Frontend Application (wird für Electron transpiliert).
- **main.js**: Electron Hauptprozess (startet internes Backend & laedt transpiliertes Frontend).
- **release/**: Finale kompilierte Desktop Executables (.exe / .dmg / .AppImage).
- **run.bat**: Interaktives Windows Startskript.
- **run.sh**: Interaktives macOS/Linux Startskript.

## ${i18n.t('generator.quickstart')}

### Windows:
Doppelklicken Sie auf die \`run.bat\` im Hauptverzeichnis (oder führen Sie sie im Terminal aus).

### macOS / Linux:
Machen Sie die \`run.sh\` ausführbar und starten Sie sie im Terminal:
\`\`\`bash
chmod +x run.sh
./run.sh
\`\`\`

Oder manuell starten:
1. \`npm run install-all\`
2. \`electron .\` (oder \`npm start\`) -> Transpiliert das Frontend bei Bedarf automatisch und startet die Anwendung ohne Dev-Server-Anzeige.

## Entwicklungsmodus (Hot Reloading)

\`\`\`bash
npm run dev
\`\`\`

## Datenbank-Optionen

Das Backend unterstützt:
- **SQLite**: Einbettbare Datei (\`database.sqlite\`), perfekt für Offline-Desktop-Anwendungen ohne Serverinstallation.
- **MySQL / PostgreSQL / MSSQL**: Externe Datenbankserver über Verbindungsparameter in \`Backend/.env\`.
`;

  files.push({ name: 'README.md', path: `${root}/README.md`, content: readmeContent, language: 'markdown' });

  return files;
};
