export const generateApiController = (
  config: NextcloudAppConfig,
  tables: Table[] = []
): string => {
  const namespace = `OCA\\${toPascalCase(config.appId || 'dbs_custom_app')}\\Controller`;

  return `<?php
declare(strict_types=1);

namespace ${namespace};

use OCP\AppFramework\ApiController as BaseApiController;
use OCP\AppFramework\Http\DataResponse;
use OCP\AppFramework\Http\Attribute\NoAdminRequired;
use OCP\AppFramework\Http\Attribute\NoCSRFRequired;
use OCP\AppFramework\Http\Attribute\CORS;
use OCP\IRequest;
use OCP\IUserSession;
use OCP\IDBConnection;

/**
 * Global Schema & System Info API Controller
 * Auto-generated by DB Studio Pro with Dependency Injection & Modern Attributes
 */
class ApiController extends BaseApiController {

    private IUserSession $userSession;
    private IDBConnection $db;

    public function __construct(
        string $AppName,
        IRequest $request,
        IUserSession $userSession,
        IDBConnection $db
    ) {
        parent::__construct($AppName, $request);
        $this->userSession = $userSession;
        $this->db = $db;
    }

    #[NoAdminRequired]
    ${config.enablePublicNoCSRF ? '#[NoCSRFRequired]\n    ' : ''}#[CORS]
    public function getSchema(): DataResponse {
        $tables = [
${tables.map(t => `            '${t.name}' => [
                'columns' => [${(t.fields || []).map(c => `'${c.name}' => ['type' => '${c.type}', 'nullable' => ${c.isNullable || c.allowNull ? 'true' : 'false'}, 'isPk' => ${c.isPrimaryKey ? 'true' : 'false'}]`).join(', ')}],
                'recordsCount' => 0
            ]`).join(',\n')}
        ];

        return new DataResponse([
            'appId' => '${config.appId}',
            'appName' => '${config.appName}',
            'version' => '${config.version}',
            'tables' => $tables,
            'user' => $this->userSession->getUser() ? $this->userSession->getUser()->getUID() : null
        ]);
    }

    #[NoAdminRequired]
    ${config.enablePublicNoCSRF ? '#[NoCSRFRequired]\n    ' : ''}#[CORS]
    public function getStats(): DataResponse {
        return new DataResponse([
            'status' => 'operational',
            'timestamp' => date('c'),
            'tableCount' => ${tables.length},
            'databasePrefix' => '${config.tablePrefix || 'oc_dbs_'}'
        ]);
    }
}
`;
};

export const generateTableController = (
  table: Table,
  config: NextcloudAppConfig
): string => {
  const appPascal = toPascalCase(config.appId || 'dbs_custom_app');
  const tablePascal = toPascalCase(table.name);
  const namespace = `OCA\\${appPascal}\\Controller`;
  const serviceClass = `${tablePascal}Service`;

  // Get field params for create/update
  const nonPkCols = (table.fields || []).filter(c => !c.isPrimaryKey);
  const paramArgs = nonPkCols.map(c => {
    const phpType = getPhpType(c.type);
    const isNullable = c.isNullable || c.allowNull;
    const nullable = isNullable ? '?' : '';
    const defaultVal = isNullable ? ' = null' : '';
    return `${nullable}${phpType} $${c.name}${defaultVal}`;
  }).join(', ');

  const updateParamArgs = `int|string $id, ` + paramArgs;

  return `<?php
declare(strict_types=1);

namespace ${namespace};

use OCP\AppFramework\ApiController;
use OCP\AppFramework\Http\DataResponse;
use OCP\AppFramework\Http\Http;
use OCP\AppFramework\Http\Attribute\NoAdminRequired;
use OCP\AppFramework\Http\Attribute\NoCSRFRequired;
use OCP\AppFramework\Http\Attribute\CORS;
use OCP\IRequest;
use OCA\\${appPascal}\\Service\\${serviceClass};

/**
 * Controller für Tabelle: ${table.name}
 *
 * Nutzt automatische Parameter-Injektion von Nextcloud:
 * JSON-Body-Felder im Request werden direkt auf die Parameter-Variablen gemappt!
 */
class ${tablePascal}Controller extends ApiController {

    private ${serviceClass} $service;

    public function __construct(
        string $AppName,
        IRequest $request,
        ${serviceClass} $service
    ) {
        parent::__construct($AppName, $request);
        $this->service = $service;
    }

    #[NoAdminRequired]
    ${config.enablePublicNoCSRF ? '#[NoCSRFRequired]\n    ' : ''}#[CORS]
    public function getAll(int $limit = 100, int $offset = 0, ?string $search = null): DataResponse {
        $items = $this->service->findAll($limit, $offset, $search);
        return new DataResponse($items);
    }

    #[NoAdminRequired]
    ${config.enablePublicNoCSRF ? '#[NoCSRFRequired]\n    ' : ''}#[CORS]
    public function getById(int|string $id): DataResponse {
        $item = $this->service->findById($id);
        if (!$item) {
            return new DataResponse(['error' => 'Datensatz nicht gefunden'], Http::STATUS_NOT_FOUND);
        }
        return new DataResponse($item);
    }

    #[NoAdminRequired]
    ${config.enablePublicNoCSRF ? '#[NoCSRFRequired]\n    ' : ''}#[CORS]
    public function create(${paramArgs}): DataResponse {
        // Nextcloud mappt die JSON-Body-Keys {"key": "val"} automatisch in die Methodenargumente
        $data = [
${nonPkCols.map(c => `            '${c.name}' => $${c.name}`).join(',\n')}
        ];

        try {
            $created = $this->service->create($data);
            return new DataResponse($created, Http::STATUS_CREATED);
        } catch (\\Exception $e) {
            return new DataResponse(['error' => $e->getMessage()], Http::STATUS_BAD_REQUEST);
        }
    }

    #[NoAdminRequired]
    ${config.enablePublicNoCSRF ? '#[NoCSRFRequired]\n    ' : ''}#[CORS]
    public function update(${updateParamArgs}): DataResponse {
        $data = [
${nonPkCols.map(c => `            '${c.name}' => $${c.name}`).join(',\n')}
        ];

        try {
            $updated = $this->service->update($id, $data);
            if (!$updated) {
                return new DataResponse(['error' => 'Datensatz nicht gefunden'], Http::STATUS_NOT_FOUND);
            }
            return new DataResponse($updated);
        } catch (\\Exception $e) {
            return new DataResponse(['error' => $e->getMessage()], Http::STATUS_BAD_REQUEST);
        }
    }

    #[NoAdminRequired]
    ${config.enablePublicNoCSRF ? '#[NoCSRFRequired]\n    ' : ''}#[CORS]
    public function delete(int|string $id): DataResponse {
        $success = $this->service->delete($id);
        if (!$success) {
            return new DataResponse(['error' => 'Datensatz nicht gefunden oder konnte nicht gelöscht werden'], Http::STATUS_NOT_FOUND);
        }
        return new DataResponse(['success' => true], Http::STATUS_OK);
    }

    #[NoAdminRequired]
    ${config.enablePublicNoCSRF ? '#[NoCSRFRequired]\n    ' : ''}#[CORS]
    public function batchInsert(array $rows = []): DataResponse {
        $count = $this->service->batchInsert($rows);
        return new DataResponse(['inserted' => $count], Http::STATUS_CREATED);
    }
}
`;
};

const getPhpType = (type: string): string => {
  const t = type.toLowerCase();
  if (t.includes('int')) return 'int';
  if (t.includes('float') || t.includes('double') || t.includes('decimal') || t.includes('currency')) return 'float';
  if (t.includes('bool')) return 'bool';
  if (t.includes('array') || t.includes('json')) return 'array';
  return 'string';
};

const toPascalCase = (str: string): string => {
  return str
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .split(' ')
    .filter(Boolean)
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join('');
};
