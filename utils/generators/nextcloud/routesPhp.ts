import { Table, Query } from '../../../types/index';
import { NextcloudAppConfig } from '../../../types/nextcloud';

export const generateRoutesPhp = (
  config: NextcloudAppConfig,
  tables: Table[] = [],
  queries: Query[] = []
): string => {
  const routes: string[] = [];

  // Page View Controller
  routes.push(`        // Haupt-Frontend Page (Vue 3 Single Page App)
        ['name' => 'page#index', 'url' => '/', 'verb' => 'GET'],
        ['name' => 'page#view_table', 'url' => '/table/{tableName}', 'verb' => 'GET'],
        ['name' => 'page#view_form', 'url' => '/form/{formId}', 'verb' => 'GET'],`);

  // Generic Meta & Health
  routes.push(`\n        // Meta & Schema Info API
        ['name' => 'api#get_schema', 'url' => '/api/v1/schema', 'verb' => 'GET'],
        ['name' => 'api#get_stats', 'url' => '/api/v1/stats', 'verb' => 'GET'],`);

  // Table CRUD Endpoints
  tables.forEach(table => {
    const slug = table.name.toLowerCase().replace(/[^a-z0-9_]+/g, '_');
    routes.push(`\n        // CRUD Endpunkte für Tabelle: ${table.name}
        ['name' => '${slug}#get_all', 'url' => '/api/v1/${slug}', 'verb' => 'GET'],
        ['name' => '${slug}#get_by_id', 'url' => '/api/v1/${slug}/{id}', 'verb' => 'GET'],
        ['name' => '${slug}#create', 'url' => '/api/v1/${slug}', 'verb' => 'POST'],
        ['name' => '${slug}#update', 'url' => '/api/v1/${slug}/{id}', 'verb' => 'PUT'],
        ['name' => '${slug}#delete', 'url' => '/api/v1/${slug}/{id}', 'verb' => 'DELETE'],
        ['name' => '${slug}#batch_insert', 'url' => '/api/v1/${slug}/batch', 'verb' => 'POST'],`);
  });

  // Queries / Views Endpoints
  queries.forEach(query => {
    const slug = query.name.toLowerCase().replace(/[^a-z0-9_]+/g, '_');
    routes.push(`\n        // Abfrage / View: ${query.name}
        ['name' => 'query#run_${slug}', 'url' => '/api/v1/queries/${slug}', 'verb' => 'GET'],`);
  });

  return `<?php
declare(strict_types=1);

/**
 * Nextcloud App REST API & Page Routes
 * Auto-generated by DB Studio Pro
 *
 * Pattern:
 * 'name' => 'controller#method_name'
 * Aus 'api#get_items' wird automatisch $apiController->getItems() aufgerufen.
 */

return [
    'routes' => [
${routes.join('\n')}
    ]
];
`;
};
