
import { Table, Query, VirtualFile, Relationship, BackendConfig, Form, Report } from '../../types/index';
import { generateReactConfigs } from './react/config';
import { generateJsxForLayout, collectLookups } from './react/components';
import { resolveType, isNullable, toCamelCase, toPascalCase, toKebabCase } from './common';

export const generateReact = (tables: Table[], relationships: Relationship[], queries: Query[], config: BackendConfig, forms: Form[] = [], reports: Report[] = []): VirtualFile[] => {
  const files: VirtualFile[] = [];
  const root = `Frontend`;

  // 1. Configs
  files.push(...generateReactConfigs(config, root));

  // 2. API & Types
  const apiService = `import axios from 'axios';
const API_URL = 'http://localhost:${config.port}/api';
export const api = axios.create({ baseURL: API_URL });
export const get = async <T>(endpoint: string) => (await api.get<T>(endpoint)).data;
export const post = async <T>(endpoint: string, data: any) => (await api.post<T>(endpoint, data)).data;
export const put = async <T>(endpoint: string, data: any) => (await api.put<T>(endpoint, data)).data;
export const remove = async (endpoint: string) => await api.delete(endpoint);`;
  files.push({ name: 'api.ts', path: `${root}/src/services/api.ts`, content: apiService, language: 'typescript' });

  let typesContent = '';
  tables.forEach(table => {
    const props = table.fields.map(f => `  ${toCamelCase(f.name)}${isNullable(f) ? '?' : ''}: ${resolveType(f, 'typescript')};`);
    typesContent += `export interface ${table.name} {\n${props.join('\n')}\n}\n\n`;
  });
  files.push({ name: 'types.ts', path: `${root}/src/types/index.ts`, content: typesContent, language: 'typescript' });

  // 3. Components (Lists & Forms)
  const routes: string[] = [];
  const imports: string[] = [];

  // --- Sidebar Component Generation ---
  const sidebarContent = `import React from 'react';
import { Link, useLocation } from 'react-router-dom';
import { Layout, Table, FileText, Database } from 'lucide-react';

export const Sidebar = () => {
  const location = useLocation();
  const isActive = (path: string) => location.pathname.startsWith(path) ? 'bg-slate-700 text-white' : 'text-slate-300 hover:bg-slate-700 hover:text-white';

  return (
    <aside className="w-64 bg-slate-900 text-white flex-shrink-0 flex flex-col h-screen">
      <div className="p-4 font-bold text-xl border-b border-slate-700 flex items-center gap-2">
        <Database size={20} /> ${config.projectName}
      </div>
      <nav className="flex-1 overflow-y-auto py-4 space-y-6">
        
        <div>
            <div className="px-4 text-xs font-bold text-slate-500 uppercase tracking-wider mb-2">Daten</div>
            <div className="space-y-1 px-2">
                ${tables.map(t => `
                <Link to="/${t.name.toLowerCase()}" className={\`flex items-center gap-2 px-3 py-2 rounded text-sm transition-colors \${isActive('/${t.name.toLowerCase()}')}\`}>
                    <Table size={16}/> ${t.name}
                </Link>`).join('\n                ')}
            </div>
        </div>

        <div>
            <div className="px-4 text-xs font-bold text-slate-500 uppercase tracking-wider mb-2">Formulare</div>
            <div className="space-y-1 px-2">
                ${forms.map(f => `
                <Link to="/forms/${toPascalCase(f.name).toLowerCase()}Form/new" className={\`flex items-center gap-2 px-3 py-2 rounded text-sm transition-colors \${isActive('/forms/${toPascalCase(f.name).toLowerCase()}Form')}\`}>
                    <Layout size={16}/> ${f.name}
                </Link>`).join('\n                ')}
            </div>
        </div>

        <div>
            <div className="px-4 text-xs font-bold text-slate-500 uppercase tracking-wider mb-2">Berichte</div>
            <div className="space-y-1 px-2">
                ${reports.map(r => `
                <Link to="/reports/${toPascalCase(r.name).toLowerCase()}Report" className={\`flex items-center gap-2 px-3 py-2 rounded text-sm transition-colors \${isActive('/reports/${toPascalCase(r.name).toLowerCase()}Report')}\`}>
                    <FileText size={16}/> ${r.name}
                </Link>`).join('\n                ')}
            </div>
        </div>

      </nav>
      <div className="p-4 border-t border-slate-700 text-xs text-slate-500 text-center">
        Generated by DB Studio Pro
      </div>
    </aside>
  );
};`;
  files.push({ name: 'Sidebar.tsx', path: `${root}/src/components/Sidebar.tsx`, content: sidebarContent, language: 'typescript' });


  // Lists
  tables.forEach(table => {
      const listName = `${table.name}List`;
      const pk = toCamelCase(table.fields.find(f=>f.isPrimaryKey)?.name || 'id');
      const content = `import React, { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { ${table.name} } from '../../types';
import { get, remove } from '../../services/api';
import { Trash2, Edit, Plus } from 'lucide-react';

export const ${listName} = () => {
  const [items, setItems] = useState<${table.name}[]>([]);
  useEffect(() => { get<${table.name}[]>('${table.name.toLowerCase()}').then(setItems); }, []);
  const handleDelete = (id: any) => { if(confirm('Löschen?')) remove(\`${table.name.toLowerCase()}/\${id}\`).then(() => get<${table.name}[]>('${table.name.toLowerCase()}').then(setItems)); };
  return (
    <div className="p-6">
      <div className="flex justify-between mb-4"><h1 className="text-2xl font-bold">${table.name}</h1><Link to="/${table.name.toLowerCase()}/new" className="bg-blue-600 text-white px-4 py-2 rounded flex gap-2 items-center"><Plus size={16}/> Neu erstellen</Link></div>
      <div className="bg-white shadow rounded overflow-hidden border border-slate-200">
        <table className="w-full text-left">
          <thead className="bg-slate-50 border-b"><tr>
            ${table.fields.map(f => `<th className="p-4 font-semibold text-sm text-slate-600">${f.name}</th>`).join('')}
            <th className="p-4 text-right font-semibold text-sm text-slate-600">Aktionen</th>
          </tr></thead>
          <tbody className="divide-y divide-slate-100">
            {items.map(i => (
                <tr key={i.${pk}} className="hover:bg-slate-50">
                    ${table.fields.map(f => `<td className="p-4 text-sm text-slate-800">{i.${toCamelCase(f.name)}}</td>`).join('')}
                    <td className="p-4 flex justify-end gap-2">
                        <button onClick={()=>handleDelete(i.${pk})} className="text-red-500 hover:text-red-700 transition-colors"><Trash2 size={18}/></button>
                    </td>
                </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
};`;
      files.push({ name: `${listName}.tsx`, path: `${root}/src/pages/${table.name}/${listName}.tsx`, content, language: 'typescript' });
      imports.push(`import { ${listName} } from './pages/${table.name}/${listName}';`);
      routes.push(`<Route path="/${table.name.toLowerCase()}" element={<${listName} />} />`);
  });

  // Forms (Custom)
  forms.forEach(form => {
      const compName = `${toPascalCase(form.name)}Form`;
      const sourceTable = tables.find(t => t.id === form.sourceId);
      if(!sourceTable) return;
      
      const lookups = form.layout ? collectLookups(form.layout, tables) : [];
      const layoutJsx = form.layout ? generateJsxForLayout(form.layout, tables) : 'Empty';
      
      const content = `import React, { useEffect, useState } from 'react';
import { useNavigate, useParams } from 'react-router-dom';
import { get, post, put } from '../../services/api';
import { Save } from 'lucide-react';

export const ${compName} = () => {
  const { id } = useParams(); const navigate = useNavigate();
  const [data, setData] = useState<any>({});
  ${lookups.map(l => `const [${l.variableName}, set${l.variableName}] = useState<any[]>([]);`).join('\n')}

  useEffect(() => {
      ${lookups.map(l => `get('${l.endpoint}').then(set${l.variableName});`).join('\n')}
      if (id && id !== 'new') get(\`${sourceTable.name.toLowerCase()}/\${id}\`).then(setData);
  }, [id]);

  const handleSubmit = (e: React.FormEvent) => { e.preventDefault(); (id && id!=='new' ? put(\`${sourceTable.name.toLowerCase()}/\${id}\`, data) : post('${sourceTable.name.toLowerCase()}', data)).then(() => navigate(-1)); };

  return (
    <div className="p-8 max-w-5xl mx-auto">
      <div className="bg-white p-8 rounded-lg shadow-md border border-slate-200">
          <h1 className="text-2xl font-bold mb-6 pb-2 border-b text-slate-800">${form.name}</h1>
          <form onSubmit={handleSubmit}>
            ${layoutJsx}
            <div className="mt-8 flex justify-end">
                <button type="submit" className="bg-blue-600 hover:bg-blue-700 text-white px-6 py-2 rounded font-medium flex gap-2 items-center transition-colors">
                    <Save size={18}/> Speichern
                </button>
            </div>
          </form>
      </div>
    </div>
  );
};`;
      files.push({ name: `${compName}.tsx`, path: `${root}/src/pages/forms/${compName}.tsx`, content, language: 'typescript' });
      imports.push(`import { ${compName} } from './pages/forms/${compName}';`);
      routes.push(`<Route path="/forms/${compName.toLowerCase()}/:id" element={<${compName} />} />`);
      routes.push(`<Route path="/${sourceTable.name.toLowerCase()}/:id" element={<${compName} />} />`); 
  });

  // Reports
  reports.forEach(report => {
      const compName = `${toPascalCase(report.name)}Report`;
      const sourceTable = tables.find(t => t.id === report.sourceId);
      const endpoint = sourceTable ? sourceTable.name.toLowerCase() : 'unknown';
      const cols = report.columns || [];

      const content = `import React, { useEffect, useState } from 'react';
import { get } from '../../services/api';

export const ${compName} = () => {
  const [data, setData] = useState<any[]>([]);
  useEffect(() => { get('${endpoint}').then(setData); }, []);

  return (
    <div className="p-8 bg-gray-50 min-h-screen">
      <div className="max-w-6xl mx-auto bg-white shadow-lg p-10">
        <h1 className="text-3xl font-bold mb-6 border-b-2 border-black pb-4">${report.name}</h1>
        <table className="w-full text-sm text-left">
            <thead>
                <tr className="border-b-2 border-black">
                    ${cols.map(c => `<th className="p-2 font-bold uppercase text-slate-600">${c.label}</th>`).join('')}
                </tr>
            </thead>
            <tbody>
                {data.length > 0 ? data.map((item, i) => (
                    <tr key={i} className="border-b hover:bg-slate-50">
                        ${cols.map(c => `<td className="p-2">{item.${toCamelCase(c.label)}}</td>`).join('')}
                    </tr>
                )) : (
                    <tr><td colSpan={${cols.length}} className="p-4 text-center text-slate-500 italic">Keine Daten vorhanden.</td></tr>
                )}
            </tbody>
        </table>
      </div>
    </div>
  );
};`;
      files.push({ name: `${compName}.tsx`, path: `${root}/src/pages/reports/${compName}.tsx`, content, language: 'typescript' });
      imports.push(`import { ${compName} } from './pages/reports/${compName}';`);
      routes.push(`<Route path="/reports/${compName.toLowerCase()}" element={<${compName} />} />`);
  });

  // App.tsx
  const appTsx = `import React from 'react';
import { BrowserRouter, Routes, Route } from 'react-router-dom';
import { Sidebar } from './components/Sidebar';
${imports.join('\n')}

function App() {
  return (
    <BrowserRouter>
      <div className="flex min-h-screen bg-gray-100 font-sans text-slate-800">
        <Sidebar />
        <main className="flex-1 overflow-auto">
          <Routes>
            <Route path="/" element={<div className="p-10 text-slate-500 text-center mt-20">
                <h2 className="text-2xl font-bold mb-2">Willkommen im Dashboard</h2>
                <p>Wählen Sie eine Option aus dem Menü.</p>
            </div>} />
            ${routes.join('\n            ')}
          </Routes>
        </main>
      </div>
    </BrowserRouter>
  );
}
export default App;`;
  files.push({ name: 'App.tsx', path: `${root}/src/App.tsx`, content: appTsx, language: 'typescript' });
  files.push({ name: 'main.tsx', path: `${root}/src/main.tsx`, content: `import React from 'react'; import ReactDOM from 'react-dom/client'; import App from './App'; import './index.css'; ReactDOM.createRoot(document.getElementById('root')!).render(<React.StrictMode><App /></React.StrictMode>);`, language: 'typescript' });
  files.push({ name: 'index.html', path: `${root}/index.html`, content: `<!doctype html><html lang="en"><head><title>${config.projectName}</title></head><body><div id="root"></div><script type="module" src="/src/main.tsx"></script></body></html>`, language: 'html' });

  return files;
};
